def cpp_locals(function):
	lines = []
	for param in function.params:
		if param.kind == "scalar" and param.type == "bool":
			lines.append(f"const bool {param.name} = {param.name}In != 0;")
		elif param.kind == "enum":
			cpp = function.catalog.enums[param.type].cpp
			cast = "std::bit_cast" if function.catalog.enums[param.type].handle else "static_cast"
			lines.append(f"const {cpp} {param.name} = {cast}<{cpp}>({param.name}In);")
		elif param.kind == "value":
			fields = ", ".join(param.name + field.upper() for field in VALUES[param.type])
			lines.append(f"const ::Shalltear::{param.type} {param.name}({fields});")
		elif param.kind == "string":
			lines.append(f"const std::string_view {param.name} = View({param.name}In);")
		elif param.kind == "span":
			items = ("" if param.out else "const ") + span_element(param, function.catalog, False)
			lines.append(f"const std::span<{items}> {param.name}({param.name}Data, static_cast<size_t>({param.name}Count));")
	return lines


def cpp_objects(function):
	lines = []
	for param in function.params:
		if param.kind != "object":
			continue
		cpp = function.catalog.objects[param.type]
		lines.append(f"{cpp}* const {param.name} = ResolveObject<{cpp}>({param.name}Id);")
		if not param.optional:
			lines += [f"if (!{param.name}) {{", "\treturn SLT_ERR_DESTROYED;", "}"]
	return lines


def cpp_result(function):
	if function.return_kind == "value":
		return f"FromEngine({function.cpp})" if function.returns in WIDE else function.cpp
	if function.return_kind == "string":
		return f"ScriptRuntime::KeepString({function.cpp})"
	if function.return_kind == "object":
		return f"IdOf({function.cpp})"
	if function.return_kind == "enum":
		cast = "std::bit_cast" if function.catalog.enums[function.returns].handle else "static_cast"
		return f"{cast}<{c_type('enum', function.returns, function.catalog)}>({function.cpp})"
	if function.returns == "bool":
		return f"static_cast<uint8_t>(({function.cpp}) ? 1 : 0)"
	return f"static_cast<{SCALARS[function.returns][0]}>({function.cpp})"


def render_thunk(function):
	if function.slots:
		return render_slot_thunk(function)
	tabs = "\t\t"
	out = [f"{tabs}{c_return(function)} {function.thunk}({', '.join(c_parameters(function, True))}) noexcept {{"]
	if function.guarded:
		# a leaf must not reach C# (FlushDirty would)
		flushes = not function.any_thread and not function.leaf
		out += [f"{tabs}\t{line}" for line in cpp_objects(function)]
		out.append(f"{tabs}\tconst int32_t status = ScriptRuntime::Guard([&] {{" if flushes else f"{tabs}\treturn ScriptRuntime::Guard([&] {{")
		out += [f"{tabs}\t\t{line}" for line in cpp_locals(function)]
		if function.return_kind == "void":
			out.append(f"{tabs}\t\t{function.cpp};")
		elif function.return_kind == "value" and function.returns not in WIDE:
			out.append(f"{tabs}\t\t::new (static_cast<void*>(outResult)) ::Shalltear::{function.returns}({function.cpp});")
		else:
			out.append(f"{tabs}\t\t*outResult = {cpp_result(function)};")
		out.append(f"{tabs}\t}});")
		if flushes:
			out += [f"{tabs}\tManagedTypes::FlushDirty();", f"{tabs}\treturn status;"]
	else:
		out += [f"{tabs}\t{line}" for line in cpp_locals(function)]
		out.append(f"{tabs}\tstatic_assert(noexcept({function.cpp}));")
		out.append(f"{tabs}\t{function.cpp};" if function.return_kind == "void" else f"{tabs}\treturn {cpp_result(function)};")
	out.append(f"{tabs}}}")
	return out


