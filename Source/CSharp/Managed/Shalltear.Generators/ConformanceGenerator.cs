using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Shalltear.Generators;

[Generator]
public sealed class ConformanceGenerator : IIncrementalGenerator {
	const string ATTRIBUTE = "Shalltear.Interop.ConformanceTestAttribute";

	static readonly SymbolDisplayFormat _qualified = SymbolDisplayFormat.FullyQualifiedFormat;

	public void Initialize(IncrementalGeneratorInitializationContext context) {
		IncrementalValuesProvider<(string Name, string Method)> cases = context.SyntaxProvider.ForAttributeWithMetadataName(
			ATTRIBUTE,
			static (node, _) => node is MethodDeclarationSyntax,
			static (found, _) => Describe((IMethodSymbol)found.TargetSymbol));
		context.RegisterSourceOutput(cases.Collect(), static (output, found) => {
			if (!found.IsDefaultOrEmpty) {
				output.AddSource("ConformanceTable.g.cs", SourceText.From(Render(found), Encoding.UTF8));
			}
		});
	}

	static (string Name, string Method) Describe(IMethodSymbol method) {
		string type = method.ContainingType.ToDisplayString(_qualified);
		return (method.ContainingType.Name + "." + method.Name, type + "." + method.Name);
	}

	static string Render(ImmutableArray<(string Name, string Method)> cases) {
		StringBuilder text = new();
		text.Append("// <auto-generated/>\n");
		text.Append("namespace Shalltear.Generated;\n\n");
		text.Append("static class ConformanceTable {\n");
		text.Append("\tstatic bool _registered;\n\n");
		text.Append("\t[global::System.Runtime.CompilerServices.ModuleInitializer]\n");
		text.Append("\tinternal static void Register() {\n");
		text.Append("\t\tif (_registered) {\n\t\t\treturn;\n\t\t}\n");
		text.Append("\t\t_registered = true;\n");
		foreach ((string name, string method) in cases) {
			text.Append("\t\tglobal::Shalltear.Interop.ConformanceRegistry.Add(\"").Append(name).Append("\", ").Append(method).Append(");\n");
		}
		text.Append("\t}\n}\n");
		return text.ToString();
	}
}
