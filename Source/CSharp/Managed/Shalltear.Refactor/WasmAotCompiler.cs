using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Shalltear.Refactor;

internal static class WasmAotCompiler {
	public static int Run(string compilerPath, string dllDir, string outDir, string tableOut, string cmakeOut, bool enableThreads) {
		if (!File.Exists(compilerPath)) {
			Console.Error.WriteLine($"wasm-aot: compiler not found: '{compilerPath}'");
			return 2;
		}
		if (!Directory.Exists(dllDir)) {
			Console.Error.WriteLine($"wasm-aot: dll directory not found: '{dllDir}'");
			return 2;
		}

		string fullDllDir = Path.GetFullPath(dllDir);
		string fullOutDir = Path.GetFullPath(outDir);
		Directory.CreateDirectory(fullOutDir);

		List<string> dlls = Directory.EnumerateFiles(fullDllDir, "*.dll", SearchOption.TopDirectoryOnly)
			.OrderBy(static p => Path.GetFileName(p), StringComparer.OrdinalIgnoreCase)
			.ToList();
		if (dlls.Count == 0) {
			Console.Error.WriteLine($"wasm-aot: no assemblies found in '{fullDllDir}'");
			return 2;
		}

		ConcurrentBag<(string dll, int exitCode, string output)> failures = new();
		var results = new (string dllName, string symbolName, string bcPath)[dlls.Count];
		int maxParallel = Math.Clamp(Environment.ProcessorCount, 1, 8);

		Parallel.For(0, dlls.Count, new ParallelOptions { MaxDegreeOfParallelism = maxParallel }, index => {
			string dllPath = dlls[index];
			string dllName = Path.GetFileName(dllPath);
			string stem = Path.GetFileNameWithoutExtension(dllName);
			string bcPath = Path.Combine(fullOutDir, dllName + ".bc");
			string asmPath = Path.Combine(fullOutDir, dllName + ".s");
			string bcArg = bcPath.Replace('\\', '/');
			string asmArg = asmPath.Replace('\\', '/');

			ProcessStartInfo psi = new() {
				FileName = compilerPath,
				WorkingDirectory = fullOutDir,
				UseShellExecute = false,
				RedirectStandardOutput = true,
				RedirectStandardError = true,
				CreateNoWindow = true,
			};
			psi.Environment["MONO_PATH"] = fullDllDir;
			psi.ArgumentList.Add("--llvm");
			psi.ArgumentList.Add("--wasm-exceptions");
			if (enableThreads) {
				psi.ArgumentList.Add("--wasm-gc-safepoints");
			}
			psi.ArgumentList.Add($"--aot=llvmonly,interp,static,direct-icalls,deterministic,mattr=simd,no-opt,asmonly,outfile={asmArg},llvm-outfile={bcArg}");
			psi.ArgumentList.Add(dllPath);

			using Process? proc = Process.Start(psi);
			if (proc == null) {
				failures.Add((dllName, -1, "failed to launch mono-aot-cross"));
				return;
			}
			Task<string> stdOutTask = proc.StandardOutput.ReadToEndAsync();
			Task<string> stdErrTask = proc.StandardError.ReadToEndAsync();
			proc.WaitForExit();
			string stdOut = stdOutTask.GetAwaiter().GetResult();
			string stdErr = stdErrTask.GetAwaiter().GetResult();

			try {
				if (File.Exists(asmPath)) {
					File.Delete(asmPath);
				}
			} catch {
			}

			if (proc.ExitCode != 0 || !File.Exists(bcPath)) {
				string combined = string.IsNullOrWhiteSpace(stdErr) ? stdOut : (stdOut + "\n" + stdErr);
				failures.Add((dllName, proc.ExitCode, combined.Trim()));
				return;
			}

			results[index] = (dllName, "mono_aot_module_" + SanitizeSymbol(stem) + "_info", bcArg);
		});

		if (!failures.IsEmpty) {
			foreach ((string dll, int exitCode, string output) in failures.OrderBy(static f => f.dll, StringComparer.Ordinal)) {
				Console.Error.WriteLine($"wasm-aot: failed compiling '{dll}' (exit {exitCode}): {output}");
			}
			return 1;
		}

		string? tableDir = Path.GetDirectoryName(Path.GetFullPath(tableOut));
		if (!string.IsNullOrEmpty(tableDir)) {
			Directory.CreateDirectory(tableDir);
		}
		StringBuilder table = new();
		table.Append("// GENERATED by Shalltear.Refactor --aot-web-mono. Do not edit manually.\n");
		table.Append("#include <mono/jit/jit.h>\n\n");
		foreach (var item in results) {
			table.Append($"extern void* {item.symbolName};\n");
		}
		table.Append("\nvoid ShalltearWebMonoRegisterAOTModules(void) {\n");
		foreach (var item in results) {
			table.Append($"\tmono_aot_register_module((void**){item.symbolName});\n");
		}
		table.Append("}\n");
		File.WriteAllText(tableOut, table.ToString(), new UTF8Encoding(false));

		string? cmakeDir = Path.GetDirectoryName(Path.GetFullPath(cmakeOut));
		if (!string.IsNullOrEmpty(cmakeDir)) {
			Directory.CreateDirectory(cmakeDir);
		}
		string normTable = Path.GetFullPath(tableOut).Replace('\\', '/');
		StringBuilder cmake = new();
		cmake.Append("# GENERATED by Shalltear.Refactor --aot-web-mono. Do not edit manually.\n");
		cmake.Append("set(SHALLTEAR_CSHARP_WEB_AOT ON)\n");
		cmake.Append($"set(SHALLTEAR_CSHARP_WEB_AOT_MODULE_TABLE \"{normTable}\")\n");
		cmake.Append("set(SHALLTEAR_CSHARP_WEB_AOT_BITCODE_FILES\n");
		foreach (var item in results) {
			cmake.Append($"\t\"{item.bcPath}\"\n");
		}
		cmake.Append(")\n");
		File.WriteAllText(cmakeOut, cmake.ToString(), new UTF8Encoding(false));
		return 0;
	}

	static string SanitizeSymbol(string name) {
		StringBuilder sb = new(name.Length);
		foreach (char c in name) {
			sb.Append(char.IsAsciiLetterOrDigit(c) || c == '_' ? c : '_');
		}
		return sb.ToString();
	}
}
