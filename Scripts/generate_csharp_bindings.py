class Catalog:
	def __init__(self):
		self.objects = dict(BUILT_IN_OBJECTS)
		self.wrappers = set(WRAPPERS)
		self.enums = {}
		self.structs = {}

	def type_list(self):
		return ", ".join(list(SCALARS) + list(VALUES) + list(self.objects) + list(self.enums)) + ", string, span<T>"

	def return_list(self):
		return ", ".join(["void"] + list(SCALARS) + list(VALUES) + sorted(self.wrappers, key=list(self.objects).index) + list(self.enums)) + ", string"


def fnv1a(data, seed=FNV_OFFSET):
	value = seed
	for byte in data:
		value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
	return value


def classify(type_name, catalog):
	if type_name == "void":
		return "void", type_name
	if type_name in SCALARS:
		return "scalar", type_name
	if type_name in VALUES:
		return "value", type_name
	if type_name == "string":
		return "string", type_name
	if isinstance(type_name, str) and type_name in catalog.objects:
		return "object", type_name
	if isinstance(type_name, str) and type_name in catalog.enums:
		return "enum", type_name
	match = SPAN.match(type_name) if isinstance(type_name, str) else None
	if match and ((match.group(1) in SCALARS and match.group(1) != "bool") or match.group(1) in catalog.structs):
		return "span", match.group(1)
	return None, type_name


def check_keys(found, allowed, required, path, where):
	unknown = sorted(set(found) - allowed)
	if unknown:
		raise SchemaError(f"{path.name}: {where}: unknown key '{unknown[0]}'. Use {', '.join(sorted(allowed))}")
	missing = sorted(required - set(found))
	if missing:
		raise SchemaError(f"{path.name}: {where}: '{missing[0]}' is missing")


def parse_function(raw, area, path, catalog):
	where = raw.get("id", "function") if isinstance(raw, dict) else "function"
	if not isinstance(raw, dict):
		raise SchemaError(f"{path.name}: {where}: function must be an object")
	check_keys(raw, FUNCTION_KEYS, {"id", "cpp", "returns", "params", "csharp"}, path, where)
	function = Function()
	function.catalog = catalog
	function.id = raw["id"]
	if not isinstance(function.id, str) or not IDENTIFIER.match(function.id):
		raise SchemaError(f"{path.name}: {where}: 'id' must be letters/digits")
	function.cpp = raw["cpp"]
	function.leaf = raw.get("leaf", False)
	function.any_thread = raw.get("thread", "main") == "any"
	if raw.get("thread", "main") not in ("main", "any"):
		raise SchemaError(f"{path.name}: {where}: 'thread' is '{raw['thread']}'. Use main/any")
	function.doc = raw.get("doc", "")

	function.return_kind, function.returns = classify(raw["returns"], catalog)
	if function.return_kind not in ("void", "scalar", "value", "string", "object", "enum") or (
			function.return_kind == "object" and function.returns not in catalog.wrappers):
		raise SchemaError(f"{path.name}: {where}: can't return '{raw['returns']}'. Use {catalog.return_list()}")
	function.nullable = raw.get("nullable", True)
	if "nullable" in raw and function.return_kind != "object":
		raise SchemaError(f"{path.name}: {where}: 'nullable' is for a returned object, this returns {raw['returns']}")

	function.params = []
	for entry in raw["params"]:
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: parameter must be an object")
		check_keys(entry, PARAM_KEYS, {"name", "type"}, path, where)
		kind, type_name = classify(entry["type"], catalog)
		if kind in (None, "void"):
			raise SchemaError(f"{path.name}: {where}: unknown type '{entry['type']}'. Use {catalog.type_list()}")
		if entry.get("out", False) and kind != "span":
			raise SchemaError(f"{path.name}: {where}: 'out' is for a span, '{entry['name']}' is {entry['type']}")
		if entry.get("optional", False) and kind != "object":
			raise SchemaError(f"{path.name}: {where}: 'optional' is for an object, '{entry['name']}' is {entry['type']}")
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: parameter name must be letters/digits")
		if entry["name"] in CSHARP_KEYWORDS:
			raise SchemaError(f"{path.name}: {where}: parameter '{entry['name']}' is a C# keyword. Rename it")
		function.params.append(Param(entry["name"], kind, type_name, entry.get("out", False), entry.get("optional", False)))

	csharp = raw["csharp"]
	check_keys(csharp, CSHARP_KEYS, {"member", "kind"}, path, where)
	function.member = csharp["member"]
	function.kind = csharp["kind"]
	function.conditional = csharp.get("conditional", "")
	function.relay = csharp.get("relay", False)
	function.access = csharp.get("access", "")
	if function.access not in ("", "internal"):
		raise SchemaError(f"{path.name}: {where}: 'access' is '{function.access}'. Use internal")
	if function.kind not in ("getter", "setter", "method"):
		raise SchemaError(f"{path.name}: {where}: 'kind' is '{function.kind}'. Use getter/setter/method")
	if function.relay and function.kind != "method":
		raise SchemaError(f"{path.name}: {where}: 'relay' needs a method")
	if function.kind == "getter" and (function.params or function.return_kind == "void"):
		raise SchemaError(f"{path.name}: {where}: getter must take nothing + return a value")
	if function.kind == "setter" and (len(function.params) != 1 or function.return_kind != "void"):
		raise SchemaError(f"{path.name}: {where}: setter must take 1 parameter + return void")
	if function.conditional and (function.kind != "method" or function.return_kind != "void"):
		raise SchemaError(f"{path.name}: {where}: 'conditional' needs a method returning void")
	if function.member == area.class_name:
		raise SchemaError(f"{path.name}: {where}: member '{function.member}' has the class name. Rename the member")
	if not area.test and not area.internal and not function.access and not function.doc and function.kind != "setter":
		raise SchemaError(f"{path.name}: {where}: 'doc' is missing")
	if area.instance:
		function.params.insert(0, Param("self", "object", area.instance, implicit=True))
	function.has_objects = any(param.kind == "object" for param in function.params)
	if function.leaf and function.return_kind == "string":
		raise SchemaError(f"{path.name}: {where}: 'leaf' can't return a string")
	function.guarded = not function.leaf or function.has_objects or function.return_kind == "object"
	function.table_member = area.name[0].lower() + area.name[1:] + function.id
	function.thunk = area.name + function.id
	return function


def read_area(path):
	try:
		raw = json.loads(path.read_text(encoding="utf-8"))
	except json.JSONDecodeError as error:
		raise SchemaError(f"{path.name}: not JSON ({error})") from error
	if not isinstance(raw, dict):
		raise SchemaError(f"{path.name}: file must hold an object")
	check_keys(raw, AREA_KEYS, {"area", "include", "class", "functions"}, path, "file")
	return raw


def parse_types(raw, path, catalog):
	types = []
	for entry in raw.get("types", []):
		where = entry.get("name", "type") if isinstance(entry, dict) else "type"
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: type must be an object")
		check_keys(entry, TYPE_KEYS, TYPE_KEYS, path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		if entry["base"] not in BASES:
			raise SchemaError(f"{path.name}: {where}: 'base' is '{entry['base']}'. Use {', '.join(BASES)}")
		declared = Area()
		declared.name, declared.cpp, declared.engine, declared.base, declared.doc = (
			entry["name"], entry["cpp"], entry["engine"], entry["base"], entry["doc"])
		catalog.objects[declared.name] = declared.cpp
		catalog.wrappers.add(declared.name)
		types.append(declared)
	return types


def parse_enums(raw, path, catalog):
	enums = []
	for entry in raw.get("enums", []):
		where = entry.get("name", "enum") if isinstance(entry, dict) else "enum"
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: enum must be an object")
		check_keys(entry, ENUM_KEYS, ENUM_KEYS - {"flags"}, path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		if entry["underlying"] not in ENUM_UNDERLYING:
			raise SchemaError(f"{path.name}: {where}: 'underlying' is '{entry['underlying']}'. Use {', '.join(ENUM_UNDERLYING)}")
		declared = Area()
		declared.name, declared.cpp, declared.underlying, declared.doc = entry["name"], entry["cpp"], entry["underlying"], entry["doc"]
		declared.flags = entry.get("flags", False)
		declared.values = []
		for value in entry["values"]:
			if not isinstance(value, dict):
				raise SchemaError(f"{path.name}: {where}: value must be an object")
			check_keys(value, ENUM_VALUE_KEYS, ENUM_VALUE_KEYS, path, where)
			if not isinstance(value["name"], str) or not IDENTIFIER.match(value["name"]) or not isinstance(value["value"], int):
				raise SchemaError(f"{path.name}: {where}: value needs a name of letters/digits + a number")
			declared.values.append((value["name"], value["value"], value["doc"]))
		if not declared.values:
			raise SchemaError(f"{path.name}: {where}: 'values' is empty")
		catalog.enums[declared.name] = declared
		enums.append(declared)
	return enums


def parse_structs(raw, path, catalog):
	structs = []
	for entry in raw.get("structs", []):
		where = entry.get("name", "struct") if isinstance(entry, dict) else "struct"
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: struct must be an object")
		check_keys(entry, STRUCT_KEYS, STRUCT_KEYS, path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums or entry["name"] in catalog.structs:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		declared = Area()
		declared.name, declared.doc, declared.fields = entry["name"], entry["doc"], []
		offset = 0
		declared.alignment = 1
		for field in entry["fields"]:
			if not isinstance(field, dict):
				raise SchemaError(f"{path.name}: {where}: field must be an object")
			check_keys(field, FIELD_KEYS, FIELD_KEYS, path, where)
			kind, type_name = classify(field["type"], catalog)
			if kind not in ("scalar", "value", "enum"):
				raise SchemaError(f"{path.name}: {where}: field '{field.get('name')}' can't be {field['type']}. Use a scalar, a value type or an enum")
			if not isinstance(field["name"], str) or not IDENTIFIER.match(field["name"]) or field["name"] in CSHARP_KEYWORDS:
				raise SchemaError(f"{path.name}: {where}: field name must be letters/digits + no C# keyword")
			scalar = catalog.enums[type_name].underlying if kind == "enum" else type_name
			size = 4 * len(VALUES[type_name]) if kind == "value" else SCALAR_SIZES[scalar]
			alignment = 4 if kind == "value" else size
			offset = (offset + alignment - 1) // alignment * alignment
			declared.fields.append((field["name"], kind, type_name, field["doc"], offset))
			offset += size
			declared.alignment = max(declared.alignment, alignment)
		if not declared.fields:
			raise SchemaError(f"{path.name}: {where}: 'fields' is empty")
		declared.size = (offset + declared.alignment - 1) // declared.alignment * declared.alignment
		catalog.structs[declared.name] = declared
		structs.append(declared)
	return structs


def build_area(path, raw, catalog, types, enums, structs):
	area = Area()
	area.types = types
	area.enums = enums
	area.structs = structs
	area.catalog = catalog
	area.name = raw["area"]
	if area.name != path.stem or not IDENTIFIER.match(area.name):
		raise SchemaError(f"{path.name}: 'area' is '{area.name}'. Name it like the file ({path.stem})")
	area.include = raw["include"]
	if not isinstance(raw["class"], str) or not CLASS_NAME.match(raw["class"]):
		raise SchemaError(f"{path.name}: 'class' must be a namespace + name (Shalltear.Time)")
	area.namespace, area.class_name = raw["class"].rsplit(".", 1)
	area.test = raw.get("test", False)
	area.internal = raw.get("internal", False)
	area.instance = raw.get("instance", "")
	if area.instance and area.instance not in catalog.objects:
		raise SchemaError(f"{path.name}: 'instance' is '{area.instance}'. Use {', '.join(catalog.objects)}")
	area.doc = raw.get("doc", "")
	if not area.test and not area.internal and not area.instance and not area.doc:
		raise SchemaError(f"{path.name}: 'doc' is missing")
	area.functions = [parse_function(entry, area, path, catalog) for entry in raw["functions"]]

	seen = set()
	for function in area.functions:
		if function.id in seen:
			raise SchemaError(f"{path.name}: {function.id}: 'id' is used twice")
		seen.add(function.id)
	members = {}
	for function in area.functions:
		members.setdefault(function.member, []).append(function)
	for member, group in members.items():
		kinds = sorted(function.kind for function in group)
		if kinds not in (["getter"], ["setter"], ["method"], ["getter", "setter"]):
			raise SchemaError(f"{path.name}: {group[-1].id}: member '{member}' is declared twice")
		if kinds == ["getter", "setter"]:
			getter = next(function for function in group if function.kind == "getter")
			setter = next(function for function in group if function.kind == "setter")
			value = explicit(setter)[0]
			if value.type != getter.returns or value.kind != getter.return_kind:
				raise SchemaError(f"{path.name}: {setter.id}: sets {value.type}, '{member}' gets {getter.returns}")
	return area


def explicit(function):
	return [param for param in function.params if not param.implicit]


def load_files(paths):
	catalog = Catalog()
	read = []
	for path in paths:
		raw = read_area(path)
		read.append((path, raw, parse_types(raw, path, catalog), parse_enums(raw, path, catalog)))
	return [build_area(path, raw, catalog, types, enums, parse_structs(raw, path, catalog)) for path, raw, types, enums in read]


def parse_area(path):
	return load_files([path])[0]


def load_areas(directory):
	return load_files(sorted(directory.glob("*.json"), key=lambda path: path.name))


def input_digest(directory, script):
	value = FNV_OFFSET
	for path in sorted(directory.glob("*.json"), key=lambda path: path.name):
		value = fnv1a(path.name.encode("utf-8") + b"\0" + path.read_bytes() + b"\0", value)
	return fnv1a(script.read_bytes(), value)


def layout_hash(areas):
	lines = [f"lowering {LOWERING}"] + [f"{name}{{{','.join(fields)}}}" for name, fields in VALUES.items()]
	for area in areas:
		for declared in area.enums:
			lines.append(f"enum {declared.name}:{declared.underlying}{{{','.join(f'{name}={value}' for name, value, _ in declared.values)}}}")
		for declared in area.structs:
			lines.append(f"struct {declared.name}{{{','.join(f'{name}:{type_name}' for name, _, type_name, _, _ in declared.fields)}}}")
	for area in areas:
		for function in area.functions:
			params = ",".join(("span<" + param.type + ">" if param.kind == "span" else param.type) + ("&" if param.out else "") +
							  ("?" if param.optional else "") for param in function.params)
			lines.append(f"{area.name}.{function.id}:{function.returns}({params}){'|leaf' if function.leaf else ''}")
	return fnv1a(("\n".join(lines) + "\n").encode("utf-8"))


def element(type_name):
	return ("int32_t", "int") if type_name in INTEGER_VALUES else ("float", "float")


def span_element(param, catalog, managed):
	if param.type in catalog.structs:
		return param.type if managed else "Slt" + param.type
	return SCALARS[param.type][2 if managed == "api" else 1 if managed else 0]


def c_type(kind, type_name, catalog=None):
	if kind == "void":
		return "void"
	if kind == "scalar":
		return SCALARS[type_name][0]
	if kind == "enum":
		return SCALARS[catalog.enums[type_name].underlying][0]
	if kind == "string":
		return "SltString"
	if kind == "object":
		return "uint64_t"
	return "Slt" + type_name if type_name in WIDE else "::Shalltear::" + type_name


def cs_abi_type(kind, type_name, catalog=None):
	if kind == "void":
		return "void"
	if kind == "string":
		return "SltString"
	if kind == "object":
		return "ulong"
	if kind == "enum":
		return SCALARS[catalog.enums[type_name].underlying][1]
	return SCALARS[type_name][1] if kind == "scalar" else type_name


def cs_api_type(kind, type_name):
	if kind == "void":
		return "void"
	return SCALARS[type_name][2] if kind == "scalar" else type_name


def cs_return_type(function):
	if function.return_kind == "object":
		return function.returns + ("?" if function.nullable else "")
	return cs_api_type(function.return_kind, function.returns)


def c_parameters(function, thunk):
	suffix = "In" if thunk else ""
	parts = []
	for param in function.params:
		if param.kind == "scalar":
			parts.append(f"{SCALARS[param.type][0]} {param.name}{suffix if param.type == 'bool' else ''}")
		elif param.kind == "enum":
			parts.append(f"{c_type(param.kind, param.type, function.catalog)} {param.name}{suffix}")
		elif param.kind == "value":
			parts += [f"{element(param.type)[0]} {param.name}{field.upper()}" for field in VALUES[param.type]]
		elif param.kind == "string":
			parts.append(f"SltString {param.name}{suffix}")
		elif param.kind == "object":
			parts.append(f"uint64_t {param.name}{'Id' if thunk else ''}")
		else:
			parts.append(f"{'' if param.out else 'const '}{span_element(param, function.catalog, False)}* {param.name}{'Data' if thunk else ''}")
			parts.append(f"int32_t {param.name}Count")
	if function.guarded and function.return_kind != "void":
		parts.append(f"{c_type(function.return_kind, function.returns, function.catalog)}* outResult")
	return parts


def c_return(function):
	return "int32_t" if function.guarded else c_type(function.return_kind, function.returns, function.catalog)


def render_native_header(areas, digest):
	out = [f"// {BANNER}", "#pragma once", ""]
	out += [f'#include "{header}"' for header in VALUE_HEADERS]
	out += ["", "#include <stdint.h>", "",
			f"#define SLT_BRIDGE_LAYOUT_HASH 0x{layout_hash(areas):016x}ull",
			f"#define SLT_BINDINGS_INPUT_DIGEST 0x{digest:016x}ull", "",
			"typedef struct SltString SltString;", ""]
	for name in WIDE:
		out += [f"typedef struct Slt{name} {{", f"\tfloat {', '.join(VALUES[name])};", f"}} Slt{name};", ""]
	for area in areas:
		for declared in area.structs:
			out.append(f"typedef struct Slt{declared.name} {{")
			out += [f"\t{c_type(kind, type_name, area.catalog)} {name};" for name, kind, type_name, _, _ in declared.fields]
			out += [f"}} Slt{declared.name};", ""]
	out.append("typedef struct SltBindings {")
	for area in areas:
		for function in area.functions:
			parameters = ", ".join(c_parameters(function, False)) or "void"
			out.append(f"\t{c_return(function)} (*{function.table_member})({parameters});")
	out += ["} SltBindings;", "", "namespace Shalltear::CSharpImpl::Generated {", "",
			"\tvoid FillBindings(SltBindings& table);", "", "} // namespace Shalltear::CSharpImpl::Generated", ""]
	return "\n".join(out)


def render_native_table(areas):
	out = [f"// {BANNER}", "", '#include "ScriptBridge.h"', "", "#include <cstddef>", "#include <type_traits>", "",
		   "namespace Shalltear::CSharpImpl::Generated {", ""]
	for name, fields in VALUES.items():
		size = 4 * len(fields)
		slot = f"Slt{name}" if name in WIDE else f"::Shalltear::{name}"
		out.append(f"\tstatic_assert(sizeof(::Shalltear::{name}) == {size} && std::is_trivially_copyable_v<::Shalltear::{name}>);")
		out.append(f"\tstatic_assert(sizeof({slot}) == {size} && alignof({slot}) == 4);")
		for index, field in enumerate(fields):
			out.append(f"\tstatic_assert(offsetof(::Shalltear::{name}, {field}) == {4 * index} && offsetof({slot}, {field}) == {4 * index});")
	for area in areas:
		for declared in area.structs:
			out.append(f"\tstatic_assert(sizeof(Slt{declared.name}) == {declared.size} && alignof(Slt{declared.name}) == {declared.alignment});")
			out += [f"\tstatic_assert(offsetof(Slt{declared.name}, {name}) == {offset});" for name, _, _, _, offset in declared.fields]
	out.append("")
	out += [f"\tvoid Fill{area.name}Bindings(SltBindings& table);" for area in areas]
	out += ["", "\tvoid FillBindings(SltBindings& table) {"]
	out += [f"\t\tFill{area.name}Bindings(table);" for area in areas]
	out += ["\t}", "", "} // namespace Shalltear::CSharpImpl::Generated", ""]
	return "\n".join(out)


def cpp_locals(function):
	lines = []
	for param in function.params:
		if param.kind == "scalar" and param.type == "bool":
			lines.append(f"const bool {param.name} = {param.name}In != 0;")
		elif param.kind == "enum":
			cpp = function.catalog.enums[param.type].cpp
			lines.append(f"const {cpp} {param.name} = static_cast<{cpp}>({param.name}In);")
		elif param.kind == "value":
			fields = ", ".join(param.name + field.upper() for field in VALUES[param.type])
			lines.append(f"const ::Shalltear::{param.type} {param.name}({fields});")
		elif param.kind == "string":
			lines.append(f"const std::string_view {param.name} = View({param.name}In);")
		elif param.kind == "span":
			items = ("" if param.out else "const ") + span_element(param, function.catalog, False)
			lines.append(f"const std::span<{items}> {param.name}({param.name}Data, static_cast<size_t>({param.name}Count));")
	return lines


def cpp_objects(function):
	lines = []
	for param in function.params:
		if param.kind != "object":
			continue
		cpp = function.catalog.objects[param.type]
		lines.append(f"{cpp}* const {param.name} = ResolveObject<{cpp}>({param.name}Id);")
		if not param.optional:
			lines += [f"if (!{param.name}) {{", "\treturn SLT_ERR_DESTROYED;", "}"]
	return lines


def cpp_result(function):
	if function.return_kind == "value":
		return f"FromEngine({function.cpp})" if function.returns in WIDE else function.cpp
	if function.return_kind == "string":
		return f"ScriptRuntime::KeepString({function.cpp})"
	if function.return_kind == "object":
		return f"IdOf({function.cpp})"
	if function.return_kind == "enum":
		return f"static_cast<{c_type('enum', function.returns, function.catalog)}>({function.cpp})"
	if function.returns == "bool":
		return f"static_cast<uint8_t>(({function.cpp}) ? 1 : 0)"
	return f"static_cast<{SCALARS[function.returns][0]}>({function.cpp})"


def render_thunk(function):
	tabs = "\t\t"
	out = [f"{tabs}{c_return(function)} {function.thunk}({', '.join(c_parameters(function, True))}) noexcept {{"]
	if function.guarded:
		# a leaf must not reach C# (FlushDirty would)
		flushes = not function.any_thread and not function.leaf
		out += [f"{tabs}\t{line}" for line in cpp_objects(function)]
		out.append(f"{tabs}\tconst int32_t status = ScriptRuntime::Guard([&] {{" if flushes else f"{tabs}\treturn ScriptRuntime::Guard([&] {{")
		out += [f"{tabs}\t\t{line}" for line in cpp_locals(function)]
		if function.return_kind == "void":
			out.append(f"{tabs}\t\t{function.cpp};")
		elif function.return_kind == "value" and function.returns not in WIDE:
			out.append(f"{tabs}\t\t::new (static_cast<void*>(outResult)) ::Shalltear::{function.returns}({function.cpp});")
		else:
			out.append(f"{tabs}\t\t*outResult = {cpp_result(function)};")
		out.append(f"{tabs}\t}});")
		if flushes:
			out += [f"{tabs}\tManagedTypes::FlushDirty();", f"{tabs}\treturn status;"]
	else:
		out += [f"{tabs}\t{line}" for line in cpp_locals(function)]
		out.append(f"{tabs}\tstatic_assert(noexcept({function.cpp}));")
		out.append(f"{tabs}\t{function.cpp};" if function.return_kind == "void" else f"{tabs}\treturn {cpp_result(function)};")
	out.append(f"{tabs}}}")
	return out


def render_native_area(area):
	out = [f"// {BANNER}", "", '#include "BindingSupport.h"', "", f'#include "{area.include}"', ""]
	if area.test:
		out += ["#ifdef SLT_CSHARP_TEST_HOOKS", ""]
	out += ["namespace Shalltear::CSharpImpl::Generated {", ""]
	for declared in area.enums:
		out.append(f"\tstatic_assert(sizeof({declared.cpp}) == sizeof({SCALARS[declared.underlying][0]}));")
		out += [f"\tstatic_assert(static_cast<int64_t>({declared.cpp}::{name}) == {value});" for name, value, _ in declared.values]
		out.append("")
	out += ["\tnamespace {", ""]
	for function in area.functions:
		out += render_thunk(function) + [""]
	out += ["\t} // anonymous namespace", "", f"\tvoid Fill{area.name}Bindings(SltBindings& table) {{"]
	out += [f"\t\ttable.{function.table_member} = &{function.thunk};" for function in area.functions]
	out += ["\t}", "", "} // namespace Shalltear::CSharpImpl::Generated", ""]
	if area.test:
		out += ["#else", "", "namespace Shalltear::CSharpImpl::Generated {", "", f"\tvoid Fill{area.name}Bindings(SltBindings&) {{}}", "",
				"} // namespace Shalltear::CSharpImpl::Generated", "", "#endif", ""]
	return "\n".join(out)


def cs_pointer(function):
	types = []
	for param in function.params:
		if param.kind == "span":
			types += [span_element(param, function.catalog, True) + "*", "int"]
		elif param.kind == "value":
			types += [element(param.type)[1]] * len(VALUES[param.type])
		else:
			types.append("SltString" if param.kind == "string" else cs_abi_type(param.kind, param.type, function.catalog))
	if function.guarded:
		if function.return_kind != "void":
			types.append(cs_abi_type(function.return_kind, function.returns, function.catalog) + "*")
		types.append("int")
	else:
		types.append(cs_abi_type(function.return_kind, function.returns, function.catalog))
	return f"delegate* unmanaged{'[SuppressGCTransition]' if function.leaf else ''}<{', '.join(types)}>"


def render_managed_table(areas):
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable", "#pragma warning disable CS0649", "",
		   "using System.Runtime.InteropServices;", "", "namespace Shalltear.Interop;", "",
		   "[StructLayout(LayoutKind.Sequential)]", "internal unsafe struct SltBindings {"]
	for area in areas:
		for function in area.functions:
			out.append(f"\tpublic {cs_pointer(function)} {function.table_member};")
	out += ["}", "", "internal static unsafe class Bindings {", f"\tinternal const ulong LAYOUT_HASH = 0x{layout_hash(areas):016x};", "",
			"\tinternal static SltBindings table;", "", "\tinternal static string? FindLayoutMismatch() {"]
	for name, fields in VALUES.items():
		size = 4 * len(fields)
		local = name[0].lower() + name[1:]
		out += [f"\t\tif (sizeof({name}) != {size}) {{", f'\t\t\treturn "{name} size " + sizeof({name}) + " (engine {size})";', "\t\t}",
				f"\t\t{name} {local} = default;"]
		for index, field in enumerate(fields):
			out += [f"\t\tif ((byte*)&{local}.{field} - (byte*)&{local} != {4 * index}) {{",
					f'\t\t\treturn "{name}.{field} offset " + ((byte*)&{local}.{field} - (byte*)&{local}) + " (engine {4 * index})";', "\t\t}"]
	for area in areas:
		for declared in area.structs:
			out += [f"\t\tif (sizeof({declared.name}) != {declared.size}) {{",
					f'\t\t\treturn "{declared.name} size " + sizeof({declared.name}) + " (engine {declared.size})";', "\t\t}"]
	out += ["\t\treturn null;", "\t}", "}", ""]
	return "\n".join(out)


def xml_text(text):
	return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def cs_call(area, function, setter):
	lines = []
	member = "member" if function.relay else f'"{area.class_name}.{function.member}"'
	if not function.any_thread:
		lines += ["if (Bridge.OffMainThread) {", f"\tBridge.ThrowOffMainThread({member});", "}"]
	arguments = []
	pinned = []
	for param in function.params:
		name = "value" if setter and not param.implicit else param.name
		if param.kind == "scalar":
			arguments.append(f"{name} ? (byte)1 : (byte)0" if param.type == "bool" else name)
		elif param.kind == "enum":
			arguments.append(f"({cs_abi_type(param.kind, param.type, function.catalog)}){name}")
		elif param.kind == "value":
			arguments += [f"{name}.{field}" for field in VALUES[param.type]]
		elif param.kind == "string":
			lines.append(f"using UTF8Scratch {name}Text = new({name}, stackalloc byte[UTF8Scratch.STACK_BYTES]);")
			arguments.append(f"{name}Text.Text")
		elif param.kind == "object":
			if param.implicit:
				arguments.append("_id")
			elif param.optional:
				arguments.append(f"{name} is null ? 0UL : {name}._id")
			else:
				lines.append(f"ArgumentNullException.ThrowIfNull({name});")
				arguments.append(f"{name}._id")
		else:
			pinned.append(f"fixed ({span_element(param, function.catalog, True)}* {name}Data = {name})")
			arguments += [f"{name}Data", f"{name}.Length"]

	body = []
	is_bool = function.returns == "bool"
	cast = f"({function.returns})" if function.return_kind == "enum" else ""
	if function.guarded:
		if function.return_kind != "void":
			body.append(f"{cs_abi_type(function.return_kind, function.returns, function.catalog)} result;")
			arguments.append("&result")
		failure = f"Bridge.Failure(status, {member})" if function.has_objects else "Bridge.LastError()"
		body += [f"int status = Bindings.table.{function.table_member}({', '.join(arguments)});", "if (status != Bridge.OK) {",
				 f"\tthrow {failure};", "}"]
		if function.return_kind == "string":
			body.append("return Bridge.Text(result);")
		elif function.return_kind == "object":
			wrap = WRAPPERS.get(function.returns, f"ObjectCache.Find<{function.returns}>")
			body.append(f"return {wrap}(result){'' if function.nullable else '!'};")
		elif function.return_kind != "void":
			body.append("return result != 0;" if is_bool else f"return {cast}result;")
	else:
		call = f"Bindings.table.{function.table_member}({', '.join(arguments)})"
		if function.return_kind == "void":
			body.append(call + ";")
		else:
			body.append(f"return {call} != 0;" if is_bool else f"return {cast}{call};")
	if pinned:
		lines += pinned[:-1] + [pinned[-1] + " {"] + ["\t" + line for line in body] + ["}"]
	else:
		lines += body
	return lines


def cs_parameters(function):
	parts = []
	listed = explicit(function)
	for index, param in enumerate(listed):
		if param.kind == "string":
			parts.append(f"string {param.name}")
		elif param.kind == "span":
			parts.append(f"{'Span' if param.out else 'ReadOnlySpan'}<{span_element(param, function.catalog, 'api')}> {param.name}")
		elif param.kind == "object":
			trailing = not function.relay and all(later.kind == "object" and later.optional for later in listed[index:])
			parts.append(f"{param.type}? {param.name}{' = null' if trailing else ''}" if param.optional else f"{param.type} {param.name}")
		else:
			parts.append(f"{cs_api_type(param.kind, param.type)} {param.name}")
	if function.relay:
		parts.append("string member")
	return ", ".join(parts)


def render_managed_types(area):
	out = []
	for declared in area.enums:
		out += [f"/// <summary>{xml_text(declared.doc)}</summary>"] + (["[Flags]"] if declared.flags else [])
		out.append(f"public enum {declared.name} : {SCALARS[declared.underlying][2]} {{")
		for name, value, doc in declared.values:
			out += [f"\t/// <summary>{xml_text(doc)}</summary>", f"\t{name} = {value},"]
		out += ["}", ""]
	for declared in area.structs:
		out += [f"/// <summary>{xml_text(declared.doc)}</summary>",
				"[System.Runtime.InteropServices.StructLayout(System.Runtime.InteropServices.LayoutKind.Sequential)]",
				f"public partial struct {declared.name} {{"]
		for name, kind, type_name, doc, _ in declared.fields:
			out += [f"\t/// <summary>{xml_text(doc)}</summary>", f"\tpublic {cs_api_type(kind, type_name)} {name};"]
		out += ["}", ""]
	for declared in area.types:
		out += [f"/// <summary>{xml_text(declared.doc)}</summary>", "[EngineType(ENGINE_TYPE)]",
				f"public sealed partial class {declared.name} : {declared.base} {{", f'\tinternal const string ENGINE_TYPE = "{declared.engine}";', "",
				f"\tinternal {declared.name}(ulong id) {{", "\t\t_id = id;", "\t}", "}", ""]
	return out


def render_managed_wrappers(areas):
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable", "", "namespace Shalltear.Interop;", "",
		   "internal static partial class ObjectCache {", "\tstatic void WrapGenerated() {"]
	for area in areas:
		out += [f"\t\tWrap({declared.name}.ENGINE_TYPE, static id => new {declared.name}(id));" for declared in area.types]
	out += ["\t}", "}", ""]
	return "\n".join(out)


def render_managed_area(area):
	access = "internal" if area.test or area.internal else "public"
	static = "" if area.instance else "static "
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable", "", "using System;", ""]
	if area.namespace != "Shalltear.Interop":
		out += ["using Shalltear.Interop;", ""]
	out += [f"namespace {area.namespace};", ""]
	out += render_managed_types(area)
	if area.doc:
		out.append(f"/// <summary>{xml_text(area.doc)}</summary>")
	out.append(f"{access} {static}unsafe partial class {area.class_name} {{")

	emitted = set()
	blocks = []
	for function in area.functions:
		if function.member in emitted:
			continue
		emitted.add(function.member)
		block = []
		if function.kind == "method":
			if function.doc:
				block.append(f"\t/// <summary>{xml_text(function.doc)}</summary>")
			if function.conditional:
				block.append(f'\t[System.Diagnostics.Conditional("{function.conditional}")]')
			if any(param.kind == "string" for param in function.params):
				block.append("\t[System.Runtime.CompilerServices.SkipLocalsInit]")
			block.append(f"\t{function.access or access} {static}{cs_return_type(function)} {function.member}({cs_parameters(function)}) {{")
			block += ["\t\t" + line for line in cs_call(area, function, False)]
			block.append("\t}")
		else:
			group = [other for other in area.functions if other.member == function.member]
			getter = next((other for other in group if other.kind == "getter"), None)
			setter = next((other for other in group if other.kind == "setter"), None)
			doc = (getter.doc if getter else "") or (setter.doc if setter else "")
			if doc:
				block.append(f"\t/// <summary>{xml_text(doc)}</summary>")
			value = None if getter else explicit(setter)[0]
			if getter:
				type_name = cs_return_type(getter)
			elif value.kind == "object":
				type_name = value.type + ("?" if value.optional else "")
			else:
				type_name = cs_api_type(value.kind, value.type)
			block.append(f"\t{function.access or access} {static}{type_name} {function.member} {{")
			if getter:
				block += ["\t\tget {"] + ["\t\t\t" + line for line in cs_call(area, getter, False)] + ["\t\t}"]
			if setter:
				block += ["\t\tset {"] + ["\t\t\t" + line for line in cs_call(area, setter, True)] + ["\t\t}"]
			block.append("\t}")
		blocks.append(block)
	for index, block in enumerate(blocks):
		out += block + ([""] if index + 1 < len(blocks) else [])
	out += ["}", ""]
	return "\n".join(out)


def render(areas, digest):
	files = {
		NATIVE / "Bindings.generated.h": render_native_header(areas, digest),
		NATIVE / "Bindings.generated.cpp": render_native_table(areas),
		MANAGED / "Bindings.g.cs": render_managed_table(areas),
		MANAGED / "Wrappers.g.cs": render_managed_wrappers(areas),
	}
	for area in areas:
		files[NATIVE / f"{area.name}.generated.cpp"] = render_native_area(area)
		files[MANAGED / f"{area.name}.g.cs"] = render_managed_area(area)
	return files


def find_stale(files):
	stale = [path for path, text in files.items() if not path.exists() or path.read_bytes() != text.encode("utf-8")]
	for directory, pattern in ((NATIVE, "*.generated.*"), (MANAGED, "*.g.cs")):
		stale += [path for path in sorted(directory.glob(pattern)) if path not in files]
	return stale


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true", help="fail if the committed output differs (don't rewrite it)")
	args = parser.parse_args()

	try:
		areas = load_areas(BINDINGS)
	except SchemaError as error:
		sys.exit(str(error))
	files = render(areas, input_digest(BINDINGS, Path(__file__).resolve()))
	stale = find_stale(files)
	if args.check:
		if stale:
			sys.exit("stale generated C# bindings: " + ", ".join(path.relative_to(ROOT).as_posix() for path in stale) +
					 "\nRun: python Scripts/generate_csharp_bindings.py")
		print(f"C# bindings up to date ({sum(len(area.functions) for area in areas)} function(s) in {len(areas)} area(s))")
		return

	for path in stale:
		if path in files:
			path.parent.mkdir(parents=True, exist_ok=True)
			path.write_bytes(files[path].encode("utf-8"))
		else:
			path.unlink()
		print(f"  -> {path.relative_to(ROOT).as_posix()}")
	print(f"{sum(len(area.functions) for area in areas)} function(s) in {len(areas)} area(s), {len(stale)} file(s) written")


if __name__ == "__main__":
	main()
