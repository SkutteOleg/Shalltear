def find_sets(root):
	sets = [BindingSet("", BINDINGS, NATIVE, MANAGED)]
	for folder in sorted((root / "Source").glob("*/Bindings"), key=lambda folder: folder.parent.name):
		name = folder.parent.name
		if name != "CSharp":
			sets.append(BindingSet(name, folder, root / "Source" / ("CSharpEditor" if name == "Editor" else f"{name}CSharp") / "Private" / "Generated",
								   root / "Source" / "CSharp" / "Managed" / f"Shalltear.{name}" / "Generated"))
	return sets


class Catalog:
	def __init__(self):
		self.objects = dict(BUILT_IN_OBJECTS)
		self.abstract = {"Component"}
		self.wrappers = set(RETURNED)
		self.enums = {}
		self.structs = {}
		self.natives = {}

	def type_list(self):
		return ", ".join(list(SCALARS) + list(VALUES) + list(self.objects) + list(self.enums)) + ", string, span<T>"

	def return_list(self):
		return ", ".join(["void"] + list(SCALARS) + list(VALUES) + sorted(self.wrappers, key=list(self.objects).index) + list(self.enums)) + ", string"


def fnv1a(data, seed=FNV_OFFSET):
	value = seed
	for byte in data:
		value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
	return value


def classify(type_name, catalog):
	if type_name == "void":
		return "void", type_name
	if type_name in SCALARS:
		return "scalar", type_name
	if type_name in VALUES:
		return "value", type_name
	if type_name == "string":
		return "string", type_name
	if isinstance(type_name, str) and type_name in catalog.objects:
		return "object", type_name
	if isinstance(type_name, str) and type_name in catalog.enums:
		return "enum", type_name
	match = SPAN.match(type_name) if isinstance(type_name, str) else None
	if match and ((match.group(1) in SCALARS and match.group(1) != "bool") or match.group(1) in catalog.structs or match.group(1) in VALUES):
		return "span", match.group(1)
	if isinstance(type_name, str) and type_name in catalog.structs:
		return "struct", type_name
	if isinstance(type_name, str) and type_name in catalog.natives:
		return "native", type_name
	match = LIST.match(type_name) if isinstance(type_name, str) else None
	if match and classify(match.group(1), catalog)[0] in ("scalar", "enum", "value", "string", "object", "struct", "native"):
		return "list", match.group(1)
	if isinstance(type_name, str) and CALLBACK.match(type_name):
		returns, *taken = type_name[3:-1].split(";")
		if callback_result(returns, catalog)[0] is not None and all(callback_item(item, catalog)[0] is not None for item in taken):
			return "callback", type_name[3:-1]
	return None, type_name


def callback_result(item, catalog):
	mode = item[:4] if item.startswith(("give:", "copy:")) else ""
	kind, type_name = classify(item[5:] if mode else item, catalog)
	if kind == "list" and not mode and classify(type_name, catalog)[0] in ("scalar", "enum", "value", "struct", "native") and type_name != "bool":
		return kind, type_name, mode
	if kind not in ("void", "scalar", "enum", "value", "string", "object", "struct", "native") or (mode and kind != "native"):
		return None, type_name, mode
	return kind, type_name, mode


def callback_item(item, catalog):
	written = item.startswith("ref:")
	kind, type_name = classify(item[4:] if written else item, catalog)
	if written:
		plain = kind in ("scalar", "value", "struct") or (kind == "enum" and not catalog.enums[type_name].handle)
		return (kind if plain else None), type_name, written
	if kind not in ("scalar", "enum", "value", "string", "object", "struct", "native", "list", "span"):
		return None, type_name, written
	return kind, type_name, written


def callback_span(type_name):
	return SCALARS[type_name][2] if type_name in SCALARS else type_name


SLOT_KINDS = ("struct", "native", "list", "callback")
KEPT_LISTS = 8
KEPT_TEXTS = 16


def parse_default(entry, kind, type_name, catalog, where):
	value, name = entry["default"], entry["name"]
	if kind == "enum" and not catalog.enums[type_name].handle:
		names = [listed for listed, _, _ in catalog.enums[type_name].values]
		if value not in names:
			raise SchemaError(f"{where}: 'default' of '{name}' is {value!r}. Use {', '.join(names)}")
		return f"{type_name}.{value}"
	if kind != "scalar":
		raise SchemaError(f"{where}: 'default' is for a scalar or an enum, '{name}' is {type_name}")
	if type_name == "bool":
		if not isinstance(value, bool):
			raise SchemaError(f"{where}: 'default' of '{name}' must be true/false")
		return "true" if value else "false"
	if isinstance(value, bool) or not isinstance(value, (int, float)) or (type_name not in ("f32", "f64") and not isinstance(value, int)):
		raise SchemaError(f"{where}: 'default' of '{name}' must be a number of type {type_name}")
	if type_name in ("f32", "f64"):
		text = f"{int(value)}" if float(value).is_integer() else repr(float(value))
		return text + ("f" if type_name == "f32" else ".0" if float(value).is_integer() else "")
	if value < 0 and type_name.startswith("u"):
		raise SchemaError(f"{where}: 'default' of '{name}' must be a number of type {type_name}")
	return str(value)


def check_keys(found, allowed, required, path, where):
	unknown = sorted(set(found) - allowed)
	if unknown:
		raise SchemaError(f"{path.name}: {where}: unknown key '{unknown[0]}'. Use {', '.join(sorted(allowed))}")
	missing = sorted(required - set(found))
	if missing:
		raise SchemaError(f"{path.name}: {where}: '{missing[0]}' is missing")


def camel_case(name):
	run = re.match(r"[A-Z]*", name).end()
	head = run - 1 if run > 1 and name[run:run + 1].islower() else run
	return name[:head].lower() + name[head:]


def parse_function(raw, area, path, catalog):
	where = raw.get("id", "function") if isinstance(raw, dict) else "function"
	if not isinstance(raw, dict):
		raise SchemaError(f"{path.name}: {where}: function must be an object")
	check_keys(raw, FUNCTION_KEYS, {"id", "cpp", "returns", "params", "csharp"}, path, where)
	function = Function()
	function.catalog = catalog
	function.id = raw["id"]
	if not isinstance(function.id, str) or not IDENTIFIER.match(function.id):
		raise SchemaError(f"{path.name}: {where}: 'id' must be letters/digits")
	function.cpp = raw["cpp"]
	function.leaf = raw.get("leaf", False)
	function.any_thread = raw.get("thread", "main") == "any"
	if raw.get("thread", "main") not in ("main", "any"):
		raise SchemaError(f"{path.name}: {where}: 'thread' is '{raw['thread']}'. Use main/any")
	function.doc = raw.get("doc", "")

	function.return_kind, function.returns = classify(raw["returns"], catalog)
	returned = ("void", "scalar", "value", "string", "object", "enum") + (("struct", "native", "list") if area.slots else ())
	if function.return_kind not in returned or (function.return_kind == "object" and function.returns not in catalog.wrappers and not area.slots):
		raise SchemaError(f"{path.name}: {where}: can't return '{raw['returns']}'. Use {catalog.return_list()}")
	function.owns = raw.get("owns", False)
	listed = function.return_kind == "list" and classify(function.returns, catalog)[0] == "native"
	if function.owns and function.return_kind != "native" and not listed:
		raise SchemaError(f"{path.name}: {where}: 'owns' is for a returned native object, this returns {raw['returns']}")
	function.adopts = raw.get("adopts", False)
	function.shared = raw.get("shared", False)
	if function.shared and (function.return_kind != "native" or function.owns or function.adopts):
		raise SchemaError(f"{path.name}: {where}: 'shared' is for a returned shared_ptr of a native, without 'owns' and 'adopts'")
	if function.adopts and (function.return_kind != "native" or function.owns):
		raise SchemaError(f"{path.name}: {where}: 'adopts' is for a returned native pointer freed by the script, without 'owns'")
	function.nullable = raw.get("nullable", True)
	if "nullable" in raw and function.return_kind not in ("object", "native"):
		raise SchemaError(f"{path.name}: {where}: 'nullable' is for a returned object, this returns {raw['returns']}")

	function.params = []
	for entry in raw["params"]:
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: parameter must be an object")
		check_keys(entry, PARAM_KEYS, {"name", "type"}, path, where)
		kind, type_name = classify(entry["type"], catalog)
		if kind in (None, "void") or (kind in SLOT_KINDS and not area.slots):
			raise SchemaError(f"{path.name}: {where}: unknown type '{entry['type']}'. Use {catalog.type_list()}")
		if entry.get("out", False) and kind != "span" and (not area.slots or (kind == "list" and "cpp" not in entry)):
			raise SchemaError(f"{path.name}: {where}: 'out' is for a span, '{entry['name']}' is {entry['type']}")
		if "cpp" in entry and not (area.slots and ((kind == "list" and entry.get("out", False)) or kind == "callback")):
			raise SchemaError(f"{path.name}: {where}: 'cpp' is the container of an out list or the type of a callback, '{entry['name']}' is {entry['type']}")
		if kind == "callback" and ("cpp" not in entry or entry.get("out", False)):
			raise SchemaError(f"{path.name}: {where}: callback '{entry['name']}' needs 'cpp' (std::function type) + no 'out'")
		if entry.get("optional", False) and kind not in ("object", "native", "callback"):
			raise SchemaError(f"{path.name}: {where}: 'optional' is for an object, '{entry['name']}' is {entry['type']}")
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: parameter name must be letters/digits")
		if entry["name"] in CSHARP_KEYWORDS:
			raise SchemaError(f"{path.name}: {where}: parameter '{entry['name']}' is a C# keyword. Rename it")
		if entry["name"] == "self" and area.instance:
			raise SchemaError(f"{path.name}: {where}: parameter 'self' is the {area.instance} passed by the area. Leave it out")
		default = parse_default(entry, kind, type_name, catalog, f"{path.name}: {where}") if "default" in entry else None
		if entry.get("shared", "") not in ("", "take", "alias", "unique") or ("shared" in entry and (kind != "native" or entry.get("out", False))):
			raise SchemaError(f"{path.name}: {where}: 'shared' is take/alias/unique on a native parameter, '{entry['name']}' is {entry['type']}")
		function.params.append(Param(entry["name"], kind, type_name, entry.get("out", False), entry.get("optional", False), default=default,
									 cpp=entry.get("cpp", ""), shared=entry.get("shared", ""), borrowed=entry.get("borrowed", False)))
	copied = [param.type for param in function.params if boxed(param, catalog)] + ([function.returns] if function.owns or function.adopts else [])
	for name in copied:
		if not catalog.natives[name].owned:
			raise SchemaError(f"{path.name}: {where}: {name} is copied for the script. Mark the native 'owned'")
	for index, param in enumerate(function.params):
		if param.default is not None and any(later.default is None and not later.optional for later in function.params[index + 1:]):
			raise SchemaError(f"{path.name}: {where}: 'default' on '{param.name}' needs one on each later parameter")

	csharp = raw["csharp"]
	check_keys(csharp, CSHARP_KEYS, {"member", "kind"}, path, where)
	function.member = csharp["member"]
	function.kind = csharp["kind"]
	function.conditional = csharp.get("conditional", "")
	function.relay = csharp.get("relay", False)
	function.access = csharp.get("access", "")
	if function.access not in ("", "internal"):
		raise SchemaError(f"{path.name}: {where}: 'access' is '{function.access}'. Use internal")
	if function.kind not in ("getter", "setter", "method"):
		raise SchemaError(f"{path.name}: {where}: 'kind' is '{function.kind}'. Use getter/setter/method")
	if function.relay and function.kind != "method":
		raise SchemaError(f"{path.name}: {where}: 'relay' needs a method")
	if (function.relay or function.kind == "setter") and any(param.default is not None for param in function.params):
		raise SchemaError(f"{path.name}: {where}: 'default' needs a method without 'relay'")
	if function.kind in ("getter", "setter") and any(param.out and param.kind != "span" for param in function.params):
		raise SchemaError(f"{path.name}: {where}: an 'out' parameter needs a method")
	if function.kind != "method" and any(param.kind == "callback" for param in function.params):
		raise SchemaError(f"{path.name}: {where}: a callback needs a method")
	if function.kind == "getter" and (function.params or function.return_kind == "void"):
		raise SchemaError(f"{path.name}: {where}: getter must take nothing + return a value")
	if function.kind == "setter" and (len(function.params) != 1 or function.return_kind != "void"):
		raise SchemaError(f"{path.name}: {where}: setter must take 1 parameter + return void")
	if function.conditional and (function.kind != "method" or function.return_kind != "void"):
		raise SchemaError(f"{path.name}: {where}: 'conditional' needs a method returning void")
	if function.member == area.class_name:
		raise SchemaError(f"{path.name}: {where}: member '{function.member}' has the class name. Rename the member")
	if not area.test and not area.internal and not area.slots and not function.access and not function.doc and function.kind != "setter":
		raise SchemaError(f"{path.name}: {where}: 'doc' is missing")
	function.static = raw.get("static", False)
	if function.static and not (area.slots and area.instance):
		raise SchemaError(f"{path.name}: {where}: 'static' is for a member of an instance area with slots")
	function.mutates = raw.get("mutates", False)
	if function.mutates and (function.static or area.instance not in catalog.structs):
		raise SchemaError(f"{path.name}: {where}: 'mutates' is for a member of a struct")
	if area.instance and not function.static:
		kind = "native" if area.instance in catalog.natives else "struct" if area.instance in catalog.structs else "object"
		function.params.insert(0, Param("self", kind, area.instance, implicit=True))
	kept = [function.return_kind] + [param.kind for param in function.params if param.out]
	if kept.count("list") > KEPT_LISTS or kept.count("string") > KEPT_TEXTS:
		raise SchemaError(f"{path.name}: {where}: returns more than {KEPT_LISTS} lists or {KEPT_TEXTS} strings")
	function.has_objects = any(param.kind == "object" for param in function.params)
	if function.leaf and function.return_kind == "string":
		raise SchemaError(f"{path.name}: {where}: 'leaf' can't return a string")
	function.guarded = area.slots or not function.leaf or function.has_objects or function.return_kind == "object"
	function.slots = area.slots
	if area.slots and function.leaf:
		raise SchemaError(f"{path.name}: {where}: 'leaf' isn't for a slots area")
	touched = [classify(function.returns, catalog)[0] if function.return_kind == "list" else function.return_kind]
	touched += [classify(param.type, catalog)[0] if param.kind == "list" else param.kind for param in function.params if not param.implicit]
	if ("thread" not in raw and area.slots and not function.static and area.instance in catalog.natives and function.kind in ("getter", "setter")
			and FIELD_ACCESS.search(function.cpp) and not MEMBER_CALL.search(function.cpp) and "object" not in touched and "callback" not in touched):
		function.any_thread = True
	function.table_member = camel_case(area.name) + function.id
	function.thunk = area.name + function.id
	return function


def read_area(path):
	try:
		raw = json.loads(path.read_text(encoding="utf-8"))
	except json.JSONDecodeError as error:
		raise SchemaError(f"{path.name}: not JSON ({error})") from error
	if not isinstance(raw, dict):
		raise SchemaError(f"{path.name}: file must hold an object")
	check_keys(raw, AREA_KEYS, {"area", "include", "class", "functions"}, path, "file")
	return raw


def parse_types(raw, path, catalog):
	types = []
	for entry in raw.get("types", []):
		where = entry.get("name", "type") if isinstance(entry, dict) else "type"
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: type must be an object")
		external = entry.get("extern", False)
		if external and not raw.get("slots"):
			raise SchemaError(f"{path.name}: {where}: 'extern' is for a type of a slots area")
		required = {"name", "cpp"} if external else TYPE_KEYS - {"abstract", "extern"} - ({"doc"} if raw.get("slots") else set())
		check_keys(entry, TYPE_KEYS, required, path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		if not external and entry["base"] not in BASES and entry["base"] not in catalog.abstract:
			raise SchemaError(f"{path.name}: {where}: 'base' is '{entry['base']}'. Use {', '.join(BASES)} or an abstract type")
		declared = Area()
		declared.name, declared.cpp, declared.engine, declared.base, declared.doc = (
			entry["name"], entry["cpp"], entry.get("engine", ""), entry.get("base", ""), entry.get("doc", ""))
		declared.abstract = entry.get("abstract", False)
		declared.external = external
		catalog.objects[declared.name] = declared.cpp
		catalog.wrappers.add(declared.name)
		if declared.abstract:
			catalog.abstract.add(declared.name)
		types.append(declared)
	return types


def parse_enums(raw, path, catalog):
	enums = []
	for entry in raw.get("enums", []):
		where = entry.get("name", "enum") if isinstance(entry, dict) else "enum"
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: enum must be an object")
		check_keys(entry, ENUM_KEYS, ENUM_KEYS - {"flags"} - ({"doc"} if raw.get("slots") else set()), path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		if entry["underlying"] not in ENUM_UNDERLYING:
			raise SchemaError(f"{path.name}: {where}: 'underlying' is '{entry['underlying']}'. Use {', '.join(ENUM_UNDERLYING)}")
		declared = Area()
		declared.name, declared.cpp, declared.underlying, declared.doc = entry["name"], entry["cpp"], entry["underlying"], entry.get("doc", "")
		declared.flags = entry.get("flags", False)
		declared.handle = False
		declared.values = []
		for value in entry["values"]:
			if not isinstance(value, dict):
				raise SchemaError(f"{path.name}: {where}: value must be an object")
			check_keys(value, ENUM_VALUE_KEYS, ENUM_VALUE_KEYS - ({"doc"} if raw.get("slots") else set()), path, where)
			if not isinstance(value["name"], str) or not IDENTIFIER.match(value["name"]) or not isinstance(value["value"], int):
				raise SchemaError(f"{path.name}: {where}: value needs a name of letters/digits + a number")
			declared.values.append((value["name"], value["value"], value.get("doc", "")))
		if not declared.values:
			raise SchemaError(f"{path.name}: {where}: 'values' is empty")
		catalog.enums[declared.name] = declared
		enums.append(declared)
	for entry in raw.get("handles", []):
		where = entry.get("name", "handle") if isinstance(entry, dict) else "handle"
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: handle must be an object")
		check_keys(entry, HANDLE_KEYS, HANDLE_KEYS - {"value"} - ({"doc"} if raw.get("slots") else set()), path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		declared = Area()
		declared.name, declared.cpp, declared.underlying, declared.doc = entry["name"], entry["cpp"], "u64", entry.get("doc", "")
		declared.flags, declared.handle, declared.values, declared.value = False, True, [], None
		if "value" in entry:
			check_keys(entry["value"], HANDLE_VALUE_KEYS, HANDLE_VALUE_KEYS, path, where)
			if not isinstance(entry["value"]["name"], str) or not IDENTIFIER.match(entry["value"]["name"]) or entry["value"]["name"] in CSHARP_KEYWORDS:
				raise SchemaError(f"{path.name}: {where}: value name must be letters/digits + no C# keyword")
			declared.value = (entry["value"]["name"], entry["value"]["doc"])
		declared.bits = declared.value[0] if declared.value else "_bits"
		catalog.enums[declared.name] = declared
		enums.append(declared)
	return enums


def parse_struct(entry, raw, path, catalog):
	where = entry.get("name", "struct") if isinstance(entry, dict) else "struct"
	if not isinstance(entry, dict):
		raise SchemaError(f"{path.name}: {where}: struct must be an object")
	mirror = "cpp" in entry
	if mirror and not raw.get("slots"):
		raise SchemaError(f"{path.name}: {where}: 'cpp' is for a struct of a slots area")
	if entry.get("extern", False) and not mirror:
		raise SchemaError(f"{path.name}: {where}: 'extern' needs 'cpp', 'size' and 'align'")
	check_keys(entry, STRUCT_KEYS, {"name", "fields"} | ({"cpp", "size", "align"} if mirror else {"doc"}), path, where)
	if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
		raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
	if entry["name"] in catalog.objects or entry["name"] in catalog.enums or entry["name"] in catalog.structs:
		raise SchemaError(f"{path.name}: {where}: type is declared twice")
	declared = Area()
	declared.name, declared.doc, declared.fields = entry["name"], entry.get("doc", ""), []
	declared.cpp = entry.get("cpp", "")
	declared.external = entry.get("extern", False)
	offset = 0
	declared.alignment = 1
	for field in entry["fields"]:
		if not isinstance(field, dict):
			raise SchemaError(f"{path.name}: {where}: field must be an object")
		if field.get("access", "internal") != "internal":
			raise SchemaError(f"{path.name}: {where}: field '{field.get('name')}' has access '{field['access']}'. Use internal (or leave it out)")
		check_keys(field, FIELD_KEYS, {"name", "type", "offset"} if mirror else {"name", "type"} if "access" in field else {"name", "type", "doc"}, path, where)
		kind, type_name = classify(field["type"], catalog)
		if isinstance(field["type"], str) and field["type"] in catalog.structs:
			kind = "struct"
		if kind not in ("scalar", "value", "enum", "struct"):
			raise SchemaError(f"{path.name}: {where}: field '{field.get('name')}' can't be {field['type']}. Use a scalar, a value type, an enum or a struct")
		if not isinstance(field["name"], str) or not IDENTIFIER.match(field["name"]) or field["name"] in CSHARP_KEYWORDS:
			raise SchemaError(f"{path.name}: {where}: field name must be letters/digits + no C# keyword")
		if kind == "struct":
			size, alignment = catalog.structs[type_name].size, catalog.structs[type_name].alignment
		else:
			scalar = catalog.enums[type_name].underlying if kind == "enum" else type_name
			size = 4 * len(VALUES[type_name]) if kind == "value" else SCALAR_SIZES[scalar]
			alignment = 4 if kind == "value" else size
		offset = field["offset"] if mirror else (offset + alignment - 1) // alignment * alignment
		member = Area()
		member.name, member.kind, member.type, member.doc, member.offset = field["name"], kind, type_name, field.get("doc", ""), offset
		member.cpp = field.get("cpp", field["name"])
		member.size = size
		member.internal = "access" in field
		declared.fields.append(member)
		offset += size
		declared.alignment = max(declared.alignment, alignment)
	if not declared.fields and not declared.external:
		raise SchemaError(f"{path.name}: {where}: 'fields' is empty")
	declared.size = (offset + declared.alignment - 1) // declared.alignment * declared.alignment
	if mirror:
		declared.size, declared.alignment = entry["size"], entry["align"]
		if any(not isinstance(number, int) or isinstance(number, bool) for number in (declared.size, declared.alignment)) or any(
				member.offset + member.size > declared.size for member in declared.fields):
			raise SchemaError(f"{path.name}: {where}: 'size', 'align' and each 'offset' must be numbers inside the struct")
	catalog.structs[declared.name] = declared
	return declared


def parse_structs(read, catalog):
	names = {entry["name"] for _, raw, _, _ in read for entry in raw.get("structs", []) if isinstance(entry, dict) and isinstance(entry.get("name"), str)}
	pending = [(index, entry) for index, (_, raw, _, _) in enumerate(read) for entry in raw.get("structs", [])]
	structs = [[] for _ in read]
	while pending:
		waiting = []
		for index, entry in pending:
			fields = entry.get("fields") if isinstance(entry, dict) else None
			needs = {field.get("type") for field in fields if isinstance(field, dict)} if isinstance(fields, list) else set()
			if any(isinstance(need, str) and need in names and need not in catalog.structs and need != entry.get("name") for need in needs):
				waiting.append((index, entry))
			else:
				structs[index].append(parse_struct(entry, read[index][1], read[index][0], catalog))
		if len(waiting) == len(pending):
			index, entry = waiting[0]
			structs[index].append(parse_struct(entry, read[index][1], read[index][0], catalog))
			waiting = waiting[1:]
		pending = waiting
	return structs


def parse_natives(raw, path, catalog):
	natives = []
	for entry in raw.get("natives", []):
		where = entry.get("name", "native") if isinstance(entry, dict) else "native"
		if not isinstance(entry, dict) or not raw.get("slots"):
			raise SchemaError(f"{path.name}: {where}: 'natives' needs objects in a slots area")
		check_keys(entry, NATIVE_KEYS, {"name", "cpp"}, path, where)
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits")
		if entry["name"] in catalog.objects or entry["name"] in catalog.enums or entry["name"] in catalog.structs or entry["name"] in catalog.natives:
			raise SchemaError(f"{path.name}: {where}: type is declared twice")
		declared = Area()
		declared.name, declared.cpp, declared.doc, declared.owned = entry["name"], entry["cpp"], entry.get("doc", ""), entry.get("owned", False)
		declared.create = entry.get("create", False)
		if declared.create and not declared.owned:
			raise SchemaError(f"{path.name}: {where}: 'create' needs 'owned'")
		catalog.natives[declared.name] = declared
		natives.append(declared)
	return natives


def parse_constants(raw, path):
	constants = []
	for entry in raw.get("constants", []):
		where = entry.get("name", "constant") if isinstance(entry, dict) else "constant"
		if not isinstance(entry, dict) or not raw.get("slots"):
			raise SchemaError(f"{path.name}: {where}: 'constants' needs objects in a slots area")
		check_keys(entry, CONSTANT_KEYS, {"name", "cpp", "type", "value"}, path, where)
		if not isinstance(entry["name"], str) or not CONSTANT_NAME.match(entry["name"]) or entry["name"] in CSHARP_KEYWORDS:
			raise SchemaError(f"{path.name}: {where}: 'name' must be letters/digits/_")
		kind, value = entry["type"], entry["value"]
		if kind == "bool":
			valid = isinstance(value, bool)
		elif kind in INTEGER_RANGES:
			valid = isinstance(value, int) and not isinstance(value, bool) and INTEGER_RANGES[kind][0] <= value <= INTEGER_RANGES[kind][1]
		elif kind in ("f32", "f64"):
			valid = isinstance(value, str)
			if valid and value not in ("inf", "-inf", "nan"):
				try:
					float.fromhex(value)
				except ValueError:
					valid = False
		else:
			valid = kind == "string" and isinstance(value, str)
		if not valid:
			raise SchemaError(f"{path.name}: {where}: 'value' {value!r} isn't a {kind}. Use bool/an integer type/f32/f64 (hex text, inf, -inf, nan)/string")
		declared = Area()
		declared.name, declared.cpp, declared.type, declared.value, declared.doc = entry["name"], entry["cpp"], kind, value, entry.get("doc", "")
		constants.append(declared)
	return constants


def constant_assert(declared):
	cpp, kind, value = declared.cpp, declared.type, declared.value
	if kind == "bool":
		return f"static_assert(({cpp}) == {'true' if value else 'false'});"
	if kind == "string":
		return f"static_assert(std::string_view({cpp}) == std::string_view({json.dumps(value)}));"
	if kind in ("f32", "f64"):
		name = "float" if kind == "f32" else "double"
		if value == "nan":
			return f"static_assert(({cpp}) != ({cpp}));"
		if value in ("inf", "-inf"):
			return f"static_assert(({cpp}) == {'-' if value[0] == '-' else ''}std::numeric_limits<{name}>::infinity());"
		return f"static_assert(static_cast<{name}>({cpp}) == {value}{'f' if kind == 'f32' else ''});"
	if kind.startswith("u"):
		return f"static_assert(static_cast<uint64_t>({cpp}) == {value}ull);"
	literal = "(-9223372036854775807ll - 1)" if value == INTEGER_RANGES["i64"][0] else f"{value}ll"
	return f"static_assert(static_cast<int64_t>({cpp}) == {literal});"


def constant_literal(declared):
	kind, value = declared.type, declared.value
	if kind == "bool":
		return "true" if value else "false"
	if kind == "string":
		return json.dumps(value)
	if kind in ("f32", "f64"):
		name = "float" if kind == "f32" else "double"
		if value == "nan":
			return f"{name}.NaN"
		if value in ("inf", "-inf"):
			return f"{name}.{'Negative' if value[0] == '-' else 'Positive'}Infinity"
		number = float.fromhex(value)
		if kind == "f64":
			return repr(number)
		single = struct.unpack("f", struct.pack("f", number))[0]
		for digits in range(1, 10):
			shown = f"{single:.{digits}g}"
			if struct.unpack("f", struct.pack("f", float(shown)))[0] == single:
				break
		return shown + "f"
	if value == INTEGER_RANGES["i64"][0]:
		return "long.MinValue"
	return str(value)


def build_area(path, raw, catalog, types, enums, structs, natives=()):
	area = Area()
	area.types = types
	area.enums = enums
	area.structs = structs
	area.natives = list(natives)
	area.catalog = catalog
	area.name = raw["area"]
	if area.name != path.stem or not IDENTIFIER.match(area.name):
		raise SchemaError(f"{path.name}: 'area' is '{area.name}'. Name it like the file ({path.stem})")
	area.slots = raw.get("slots", False)
	area.includes = raw["include"] if isinstance(raw["include"], list) else [raw["include"]]
	if not area.slots and isinstance(raw["include"], list):
		raise SchemaError(f"{path.name}: 'include' is a list. Use 1 header (or a slots area)")
	area.include = area.includes[0]
	if not isinstance(raw["class"], str) or not CLASS_NAME.match(raw["class"]):
		raise SchemaError(f"{path.name}: 'class' must be a namespace + name (Shalltear.Time)")
	area.namespace, area.class_name = raw["class"].rsplit(".", 1)
	area.test = raw.get("test", False)
	area.internal = raw.get("internal", False)
	area.instance = raw.get("instance", "")
	if area.instance and area.instance not in catalog.objects and not (area.slots and (area.instance in catalog.natives or area.instance in catalog.structs)):
		raise SchemaError(f"{path.name}: 'instance' is '{area.instance}'. Use {', '.join(catalog.objects)}")
	area.doc = raw.get("doc", "")
	if not area.test and not area.internal and not area.instance and not area.doc and not area.slots:
		raise SchemaError(f"{path.name}: 'doc' is missing")
	area.functions = [parse_function(entry, area, path, catalog) for entry in raw["functions"]]
	area.prelude = raw.get("prelude", [])
	if area.prelude and (not area.slots or not isinstance(area.prelude, list) or any(not isinstance(line, str) for line in area.prelude)):
		raise SchemaError(f"{path.name}: 'prelude' is a list of C++ lines in a slots area")
	area.constants = parse_constants(raw, path)
	named = [declared.name for declared in area.constants] + [function.member for function in area.functions]
	for declared in area.constants:
		if named.count(declared.name) > 1:
			raise SchemaError(f"{path.name}: {declared.name}: member '{declared.name}' is declared twice")
	for function in area.functions:
		function.hidden = False
	for declared in area.natives:
		made = [(declared.name + "Delete", "Slots::ForgetFields(target), delete target", "void", [{"name": "target", "type": declared.name}])] if declared.owned else []
		if declared.create:
			made.append((declared.name + "New", f"new {declared.cpp}()", declared.name, []))
		for name, cpp, returns, params in made:
			function = parse_function({"id": name, "cpp": cpp, "returns": returns, "params": params,
									   "csharp": {"member": name, "kind": "method", "access": "internal"}}, area, path, catalog)
			function.params = [param for param in function.params if not param.implicit]
			function.has_objects = False
			function.static = True
			function.hidden = True
			area.functions.append(function)

	seen = set()
	for function in area.functions:
		if function.id in seen:
			raise SchemaError(f"{path.name}: {function.id}: 'id' is used twice")
		seen.add(function.id)
	members = {}
	for function in area.functions:
		if function.hidden:
			continue
		members.setdefault(function.member, []).append(function)
	for member, group in members.items():
		kinds = sorted(function.kind for function in group)
		shapes = {tuple((param.kind, param.type, param.out) for param in explicit(function)) for function in group}
		if len({function.static for function in group}) > 1:
			raise SchemaError(f"{path.name}: {group[-1].id}: member '{member}' is static in 1 place only")
		if area.slots and set(kinds) == {"method"} and len(shapes) == len(group):
			continue
		if kinds not in (["getter"], ["setter"], ["method"], ["getter", "setter"]):
			raise SchemaError(f"{path.name}: {group[-1].id}: member '{member}' is declared twice")
		if kinds == ["getter", "setter"]:
			getter = next(function for function in group if function.kind == "getter")
			setter = next(function for function in group if function.kind == "setter")
			value = explicit(setter)[0]
			if value.type != getter.returns or value.kind != getter.return_kind:
				raise SchemaError(f"{path.name}: {setter.id}: sets {value.type}, '{member}' gets {getter.returns}")
	return area


def boxed(param, catalog):
	return param.out and param.kind == "list" and classify(param.type, catalog)[0] == "native" and not param.borrowed


def explicit(function):
	return [param for param in function.params if not param.implicit]


def load_files(paths, binding_set=None, catalog=None):
	catalog = catalog or Catalog()
	binding_set = binding_set or BindingSet("", BINDINGS, NATIVE, MANAGED)
	read = []
	raws = [(path, read_area(path)) for path in paths]
	for _, raw in raws:
		catalog.abstract.update(entry["name"] for entry in raw.get("types", [])
								if isinstance(entry, dict) and entry.get("abstract") is True and isinstance(entry.get("name"), str))
	for path, raw in raws:
		read.append((path, raw, parse_types(raw, path, catalog), parse_enums(raw, path, catalog)))
	structs = parse_structs(read, catalog)
	natives = [parse_natives(raw, path, catalog) for path, raw, _, _ in read]
	areas = [build_area(path, raw, catalog, types, enums, declared, native)
			 for (path, raw, types, enums), declared, native in zip(read, structs, natives)]
	for area in areas:
		area.set = binding_set
	return areas


def load_sets(sets):
	catalog = Catalog()
	seen = {}
	for binding_set in sets:
		paths = sorted(binding_set.bindings.glob("*.json"), key=lambda path: path.name)
		binding_set.areas = load_files(paths, binding_set, catalog)
		for area in binding_set.areas:
			if area.name in seen:
				raise SchemaError(f"{area.name}.json: area is declared twice ({seen[area.name]} + {binding_set.bindings.parent.name})")
			seen[area.name] = binding_set.bindings.parent.name
	return sets


def parse_area(path):
	return load_files([path])[0]


def sets_digest(sets, script):
	value = FNV_OFFSET
	for binding_set in sets:
		for path in sorted(binding_set.bindings.glob("*.json"), key=lambda path: path.name):
			value = fnv1a(path.name.encode("utf-8") + b"\0" + path.read_bytes() + b"\0", value)
	return fnv1a(script.read_bytes(), value)


def layout_hash(areas):
	lines = [f"lowering {LOWERING}"] + [f"{name}{{{','.join(fields)}}}" for name, fields in VALUES.items()]
	for area in areas:
		for declared in area.enums:
			kind = "handle" if declared.handle else "enum"
			lines.append(f"{kind} {declared.name}:{declared.underlying}{{{','.join(f'{name}={value}' for name, value, _ in declared.values)}}}")
		for declared in area.structs:
			layout = f"@{declared.size}" + "".join(f"+{field.offset}" for field in declared.fields) + ("|extern" if declared.external else "") if declared.cpp else ""
			lines.append(f"struct {declared.name}{{{','.join(f'{field.name}:{field.type}' for field in declared.fields)}}}{layout}")
		for declared in area.natives:
			lines.append(f"native {declared.name}{'|owned' if declared.owned else ''}{'|create' if declared.create else ''}")
		for declared in area.types:
			if declared.external:
				lines.append(f"extern {declared.name}")
	for area in areas:
		for function in area.functions:
			params = ",".join((param.kind + "<" + param.type + ">" if param.kind in ("span", "list") else param.type) + ("&" if param.out else "") +
							  ("?" if param.optional else "") + ("^" + param.shared if param.shared else "") for param in function.params)
			returns = f"list<{function.returns}>" if function.return_kind == "list" else function.returns
			lines.append(f"{area.name}.{function.id}:{returns}({params}){'|leaf' if function.leaf else ''}{'|slots' if function.slots else ''}"
						 f"{'|owns' if function.owns else ''}{'|adopts' if function.adopts else ''}{'|shared' if function.shared else ''}"
						 f"{'|static' if function.static and not function.hidden else ''}")
	return fnv1a(("\n".join(lines) + "\n").encode("utf-8"))


def element(type_name):
	return ("int32_t", "int") if type_name in INTEGER_VALUES else ("float", "float")


def span_element(param, catalog, managed):
	if param.type in VALUES:
		return param.type
	if param.type in catalog.structs:
		return param.type if managed else "Slt" + param.type
	return SCALARS[param.type][2 if managed == "api" else 1 if managed else 0]


def c_type(kind, type_name, catalog=None):
	if kind == "void":
		return "void"
	if kind == "scalar":
		return SCALARS[type_name][0]
	if kind == "enum":
		return SCALARS[catalog.enums[type_name].underlying][0]
	if kind == "string":
		return "SltString"
	if kind == "object":
		return "uint64_t"
	return "Slt" + type_name if type_name in WIDE or kind == "struct" else "::Shalltear::" + type_name


def cs_abi_type(kind, type_name, catalog=None):
	if kind == "void":
		return "void"
	if kind == "string":
		return "SltString"
	if kind == "object":
		return "ulong"
	if kind == "enum":
		return SCALARS[catalog.enums[type_name].underlying][1]
	return SCALARS[type_name][1] if kind == "scalar" else type_name


def cs_api_type(kind, type_name):
	if kind == "void":
		return "void"
	return SCALARS[type_name][2] if kind == "scalar" else type_name


def cs_return_type(function):
	if function.return_kind in ("object", "native"):
		return function.returns + ("?" if function.nullable else "")
	if function.return_kind == "list":
		return cs_list_type(function.returns, function.catalog) + "[]"
	return cs_api_type(function.return_kind, function.returns)


def c_parameters(function, thunk):
	if function.slots:
		return ["const uint64_t* arguments", "uint64_t* results"]
	suffix = "In" if thunk else ""
	parts = []
	for param in function.params:
		if param.kind == "scalar":
			parts.append(f"{SCALARS[param.type][0]} {param.name}{suffix if param.type == 'bool' else ''}")
		elif param.kind == "enum":
			parts.append(f"{c_type(param.kind, param.type, function.catalog)} {param.name}{suffix}")
		elif param.kind == "value":
			parts += [f"{element(param.type)[0]} {param.name}{field.upper()}" for field in VALUES[param.type]]
		elif param.kind == "string":
			parts.append(f"SltString {param.name}{suffix}")
		elif param.kind == "object":
			parts.append(f"uint64_t {param.name}{'Id' if thunk else ''}")
		else:
			parts.append(f"{'' if param.out else 'const '}{span_element(param, function.catalog, False)}* {param.name}{'Data' if thunk else ''}")
			parts.append(f"int32_t {param.name}Count")
	if function.guarded and function.return_kind != "void":
		parts.append(f"{c_type(function.return_kind, function.returns, function.catalog)}* outResult")
	return parts


