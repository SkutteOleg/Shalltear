def cs_call(area, function, setter):
	if function.slots:
		return cs_slot_call(area, function, setter)
	lines = []
	member = "member" if function.relay else f'"{area.class_name}.{function.member}"'
	if not function.any_thread:
		lines += ["if (Bridge.OffMainThread) {", f"\tBridge.ThrowOffMainThread({member});", "}"]
	arguments = []
	pinned = []
	for param in function.params:
		name = "value" if setter and not param.implicit else param.name
		if param.kind == "scalar":
			arguments.append(f"{name} ? (byte)1 : (byte)0" if param.type == "bool" else name)
		elif param.kind == "enum" and function.catalog.enums[param.type].handle:
			arguments.append(f"{name}.{function.catalog.enums[param.type].bits}")
		elif param.kind == "enum":
			arguments.append(f"({cs_abi_type(param.kind, param.type, function.catalog)}){name}")
		elif param.kind == "value":
			arguments += [f"{name}.{field}" for field in VALUES[param.type]]
		elif param.kind == "string":
			lines.append(f"using UTF8Scratch {name}Text = new({name}, stackalloc byte[UTF8Scratch.STACK_BYTES]);")
			arguments.append(f"{name}Text.Text")
		elif param.kind == "object":
			if param.implicit:
				arguments.append("_id")
			elif param.optional:
				arguments.append(f"{name} is null ? 0UL : {name}._id")
			else:
				lines.append(f"ArgumentNullException.ThrowIfNull({name});")
				arguments.append(f"{name}._id")
		else:
			pinned.append(f"fixed ({span_element(param, function.catalog, True)}* {name}Data = {name})")
			arguments += [f"{name}Data", f"{name}.Length"]

	body = []
	is_bool = function.returns == "bool"
	cast, close = "", ""
	if function.return_kind == "enum":
		cast, close = (f"new {function.returns}(", ")") if function.catalog.enums[function.returns].handle else (f"({function.returns})", "")
	if function.guarded:
		if function.return_kind != "void":
			body.append(f"{cs_abi_type(function.return_kind, function.returns, function.catalog)} result;")
			arguments.append("&result")
		failure = f"Bridge.Failure(status, {member})" if function.has_objects else "Bridge.LastError()"
		body += [f"int status = {area.set.holder}.table.{function.table_member}({', '.join(arguments)});", "if (status != Bridge.OK) {",
				 f"\tthrow {failure};", "}"]
		if function.return_kind == "string":
			body.append("return Bridge.Text(result);")
		elif function.return_kind == "object":
			wrap = WRAPPERS.get(function.returns, f"ObjectCache.Find<{function.returns}>")
			body.append(f"return {wrap}(result){'' if function.nullable else '!'};")
		elif function.return_kind != "void":
			body.append("return result != 0;" if is_bool else f"return {cast}result{close};")
	else:
		call = f"{area.set.holder}.table.{function.table_member}({', '.join(arguments)})"
		if function.return_kind == "void":
			body.append(call + ";")
		else:
			body.append(f"return {call} != 0;" if is_bool else f"return {cast}{call}{close};")
	if pinned:
		lines += pinned[:-1] + [pinned[-1] + " {"] + ["\t" + line for line in body] + ["}"]
	else:
		lines += body
	return lines


def slot_width(kind, type_name):
	if kind == "value":
		return VALUE_SLOTS[type_name]
	return 2 if kind in ("string", "span", "list") else 1


def slot_layout(function):
	arguments, results = {}, {}
	at = 0
	for param in function.params:
		if param.out and param.kind != "span":
			continue
		arguments[param.name] = at
		at += slot_width(param.kind, param.type)
	argument_count = at
	at = 0
	if function.return_kind != "void":
		results[""] = at
		at += slot_width(function.return_kind, function.returns)
	for param in function.params:
		if param.out and param.kind != "span":
			results[param.name] = at
			at += slot_width(param.kind, param.type)
	return arguments, argument_count, results, at


def cpp_type_of(kind, type_name, catalog):
	if kind == "scalar":
		return "bool" if type_name == "bool" else SCALARS[type_name][0]
	if kind == "enum":
		return catalog.enums[type_name].cpp
	if kind == "value":
		return "::Shalltear::" + type_name
	if kind == "struct":
		return catalog.structs[type_name].cpp or "Slt" + type_name
	if kind == "object":
		return catalog.objects[type_name]
	if kind == "native":
		return catalog.natives[type_name].cpp
	return "std::string_view"


def cpp_slot_read(kind, type_name, catalog, base, offset):
	source = f"{base} + {offset}" if offset else base
	cell = f"{base}[{offset}]"
	if kind == "scalar":
		if type_name == "bool":
			return f"{cell} != 0"
		if type_name == "f32":
			return f"Slots::ToF32({cell})"
		if type_name == "f64":
			return f"Slots::ToF64({cell})"
		return f"static_cast<{SCALARS[type_name][0]}>({cell})"
	if kind == "enum":
		declared = catalog.enums[type_name]
		if declared.handle:
			return f"std::bit_cast<{declared.cpp}>({cell})"
		return f"static_cast<{declared.cpp}>(static_cast<{SCALARS[declared.underlying][0]}>({cell}))"
	if kind == "value":
		return f"Slots::Read<::Shalltear::{type_name}>({source})"
	if kind == "string":
		return f"Slots::View({source})"
	if kind == "struct":
		return f"Slots::Struct<{cpp_type_of(kind, type_name, catalog)}>({cell})"
	if kind == "native":
		return f"reinterpret_cast<{catalog.natives[type_name].cpp}*>(static_cast<uintptr_t>({cell}))"
	return f"ResolveObject<{catalog.objects[type_name]}>({cell})"


def cpp_slot_write(kind, type_name, catalog, base, offset, value, owns=False):
	target = f"{base} + {offset}" if offset else base
	cell = f"{base}[{offset}]"
	if kind == "scalar":
		if type_name == "bool":
			return f"{cell} = ({value}) ? 1 : 0;"
		if type_name == "f32":
			return f"{cell} = Slots::OfF32({value});"
		if type_name == "f64":
			return f"{cell} = Slots::OfF64({value});"
		middle = "static_cast<int64_t>" if type_name in SIGNED else ""
		return f"{cell} = static_cast<uint64_t>({middle}(static_cast<{SCALARS[type_name][0]}>({value})));"
	if kind == "enum":
		declared = catalog.enums[type_name]
		if declared.handle:
			return f"{cell} = std::bit_cast<uint64_t>({value});"
		middle = "static_cast<int64_t>" if declared.underlying in SIGNED else ""
		return f"{cell} = static_cast<uint64_t>({middle}(static_cast<{SCALARS[declared.underlying][0]}>({value})));"
	if kind == "value":
		return f"Slots::Write({target}, ::Shalltear::{type_name}({value}));"
	if kind == "string":
		return f"Slots::Text({target}, {value});"
	if kind == "struct":
		return f"Slots::StructOut<{cpp_type_of(kind, type_name, catalog)}>({cell}, {value});"
	if kind == "native":
		cpp = catalog.natives[type_name].cpp
		return f"{cell} = Slots::Box<{cpp}>({value});" if owns else f"{cell} = Slots::Pointer<{cpp}>({value});"
	if kind == "list":
		element_kind, _ = classify(type_name, catalog)
		if element_kind == "object":
			return f"Slots::KeepObjects({target}, {value});"
		if element_kind == "string":
			return f"Slots::KeepTexts({target}, {value});"
		if element_kind == "native":
			return f"Slots::KeepBoxes<{catalog.natives[type_name].cpp}>({target}, {value});" if owns else f"Slots::KeepPointers({target}, {value});"
		return f"Slots::KeepList<{cpp_type_of(element_kind, type_name, catalog)}>({target}, {value});"
	return f"{cell} = IdOf({value});"


def callback_thunk(param, catalog, inner, at):
	returns, *taken = param.type.split(";")
	name = param.name
	items = [callback_item(item, catalog) for item in taken]
	declared = ", ".join(f"{'auto&' if written else 'const auto&'} a{index}" for index, (_, _, written) in enumerate(items))
	lines = [f"{inner}{param.cpp} {name};", f"{inner}if (const auto {name}Hold = Slots::HoldCallback(arguments[{at}])) {{",
			 f"{inner}\t{name} = [{name}Hold]({declared}) -> Slots::ResultOf<{param.cpp}> {{"]
	body = inner + "\t\t"
	offsets, total = [], 0
	for kind, type_name, written in items:
		offsets.append(total)
		total += 1 if written else slot_width(kind, type_name)
	result_kind, result_type, result_mode = callback_result(returns, catalog)
	width = 0 if result_kind == "void" else slot_width(result_kind, result_type)
	lines += [f"{body}uint64_t callArguments[{max(1, total)}]{{}};", f"{body}uint64_t callResults[{max(1, width)}]{{}};"]
	for index, (kind, type_name, written) in enumerate(items):
		if written:
			lines.append(f"{body}callArguments[{offsets[index]}] = Slots::Bits(&a{index});")
		elif kind == "object":
			lines.append(f"{body}callArguments[{offsets[index]}] = Slots::IdOfItem(a{index});")
		elif kind == "struct":
			lines.append(f"{body}callArguments[{offsets[index]}] = Slots::Pointer<{cpp_type_of(kind, type_name, catalog)}>(a{index});")
		elif kind == "scalar" and type_name == "u64":
			lines.append(f"{body}callArguments[{offsets[index]}] = Slots::Bits(a{index});")
		elif kind == "span":
			lines += [f"{body}callArguments[{offsets[index]}] = Slots::Bits(a{index}.data());", f"{body}callArguments[{offsets[index] + 1}] = a{index}.size();"]
		else:
			lines.append(f"{body}{cpp_slot_write(kind, type_name, catalog, 'callArguments', offsets[index], f'a{index}')}")
	if result_kind == "struct":
		lines += [f"{body}{cpp_type_of(result_kind, result_type, catalog)} made{{}};", f"{body}callResults[0] = Slots::Bits(&made);"]
	failed = "return;" if result_kind == "void" else f"return Slots::ResultOf<{param.cpp}>();"
	lines += [f"{body}if (Slots::InvokeCallback(*{name}Hold, callArguments, callResults) != SLT_OK) {{", f"{body}\t{failed}", f"{body}}}"]
	if result_kind == "struct":
		lines.append(f"{body}return static_cast<Slots::ResultOf<{param.cpp}>>(made);")
	elif result_kind == "scalar" and result_type == "u64":
		lines.append(f"{body}return Slots::FromBits<Slots::ResultOf<{param.cpp}>>(callResults[0]);")
	elif result_kind == "list":
		element_kind, _ = classify(result_type, catalog)
		element = cpp_type_of(element_kind, result_type, catalog)
		if element_kind == "native":
			lines.append(f"{body}return Slots::Copies<Slots::ResultOf<{param.cpp}>>(std::span<{element}* const>(reinterpret_cast<{element}* const*>("
						 f"static_cast<uintptr_t>(callResults[0])), static_cast<size_t>(callResults[1])));")
		else:
			lines += [f"{body}const auto* const items = reinterpret_cast<const {element}*>(static_cast<uintptr_t>(callResults[0]));",
					  f"{body}return Slots::ResultOf<{param.cpp}>(items, items + callResults[1]);"]
	elif result_mode == "copy":
		lines += [f"{body}const auto* const made = {cpp_slot_read(result_kind, result_type, catalog, 'callResults', 0)};",
				  f"{body}return made ? static_cast<Slots::ResultOf<{param.cpp}>>(*made) : Slots::ResultOf<{param.cpp}>();"]
	elif result_kind != "void":
		lines.append(f"{body}return static_cast<Slots::ResultOf<{param.cpp}>>({cpp_slot_read(result_kind, result_type, catalog, 'callResults', 0)});")
	lines += [f"{inner}\t}};", f"{inner}}}"]
	return lines


def cs_delegate(param, catalog):
	returns, *taken = param.type.split(";")
	types = []
	for item in taken:
		kind, type_name, written = callback_item(item, catalog)
		spelled = f"Span<{callback_span(type_name)}>" if kind == "span" else cs_slot_api_type(kind, type_name, catalog)
		types.append(f"Ref<{spelled}>" if written else spelled)
	result_kind, result_type, _ = callback_result(returns, catalog)
	if result_kind == "void":
		return "Action" + (f"<{', '.join(types)}>" if types else "")
	return f"Func<{', '.join(types + [cs_slot_api_type(result_kind, result_type, catalog) + ('?' if result_kind in ('native', 'list') else '')])}>"


def callback_name(function, param):
	return f"{function.id}{param.name[0].upper()}{param.name[1:]}Callback"


def callback_helper(function, param):
	catalog = function.catalog
	returns, *taken = param.type.split(";")
	arguments = []
	at = 0
	for item in taken:
		kind, type_name, written = callback_item(item, catalog)
		if written:
			arguments.append(f"new Ref<{cs_slot_api_type(kind, type_name, catalog)}>(slots[{at}])")
			at += 1
			continue
		if kind == "span":
			arguments.append(f"new Span<{callback_span(type_name)}>((void*)slots[{at}], (int)slots[{at + 1}])")
		else:
			arguments.append(f"(slots[{at}] == 0 ? default : *({type_name}*)slots[{at}])" if kind == "struct" else cs_slot_read(kind, type_name, catalog, at, nullable=False))
		at += slot_width(kind, type_name)
	call = f"handler({', '.join(arguments)})"
	out = [f"\tstatic SlotCallback {callback_name(function, param)}({cs_delegate(param, catalog)} handler) {{", "\t\treturn (slots, results) => {"]
	kind, type_name, mode = callback_result(returns, catalog)
	if kind == "void":
		out.append(f"\t\t\t{call};")
	elif kind == "scalar" and type_name == "bool":
		out.append(f"\t\t\tresults[0] = {call} ? 1UL : 0UL;")
	elif kind == "scalar" and type_name == "f32":
		out.append(f"\t\t\tresults[0] = BitConverter.SingleToUInt32Bits({call});")
	elif kind == "scalar" and type_name == "f64":
		out.append(f"\t\t\tresults[0] = BitConverter.DoubleToUInt64Bits({call});")
	elif kind == "scalar":
		out.append(f"\t\t\tresults[0] = (ulong){'(long)' if type_name in SIGNED else ''}{call};")
	elif kind == "enum" and catalog.enums[type_name].handle:
		out.append(f"\t\t\tresults[0] = {call}.{catalog.enums[type_name].bits};")
	elif kind == "enum":
		underlying = catalog.enums[type_name].underlying
		out.append(f"\t\t\tresults[0] = (ulong){'(long)' if underlying in SIGNED else ''}({SCALARS[underlying][2]}){call};")
	elif kind == "value":
		out.append(f"\t\t\tSlotValues.Put(results, {call});")
	elif kind == "string":
		out.append(f"\t\t\tSlotCallbacks.KeepText(results, {call});")
	elif kind == "struct":
		out.append(f"\t\t\t*({type_name}*)results[0] = {call};")
	elif kind == "list":
		out.append(f"\t\t\tSlotCallbacks.{'KeepNatives' if classify(type_name, catalog)[0] == 'native' else 'KeepArray'}(results, {call});")
	elif kind == "native":
		handed = f'made.Give("{param.name}")' if mode == "give" else "made.Pointer"
		out += [f"\t\t\t{type_name}? made = {call};", f"\t\t\tresults[0] = made is null ? 0UL : {handed};"]
	else:
		out += [f"\t\t\t{type_name}? made = {call};", "\t\t\tresults[0] = made is null ? 0UL : made._id;"]
	out += ["\t\t};", "\t}"]
	return out


def render_slot_thunk(function):
	catalog = function.catalog
	arguments, _, results, _ = slot_layout(function)
	tabs = "\t\t"
	_, argument_count, _, result_count = slot_layout(function)
	out = [f"{tabs}int32_t {function.thunk}({'' if argument_count else '[[maybe_unused]] '}const uint64_t* arguments, "
		   f"{'' if result_count else '[[maybe_unused]] '}uint64_t* results) noexcept {{"]
	for param in function.params:
		if param.kind == "object" and not param.out:
			cpp = catalog.objects[param.type]
			out.append(f"{tabs}\t{cpp}* const {param.name} = ResolveObject<{cpp}>(arguments[{arguments[param.name]}]);")
			if not param.optional:
				out += [f"{tabs}\tif (!{param.name}) {{", f"{tabs}\t\treturn SLT_ERR_DESTROYED;", f"{tabs}\t}}"]
	flushes = not function.any_thread
	out.append(f"{tabs}\tconst int32_t status = ScriptRuntime::Guard([&] {{" if flushes else f"{tabs}\treturn ScriptRuntime::Guard([&] {{")
	inner = tabs + "\t\t"
	for param in function.params:
		if param.out and param.kind != "span":
			declared = (param.cpp if param.kind == "list" else f"{catalog.objects[param.type]}*" if param.kind == "object" else
						"str" if param.kind == "string" else cpp_type_of(param.kind, param.type, catalog))
			if param.kind == "native":
				declared += "*"
			out.append(f"{inner}{declared} {param.name}{{}};")
			continue
		if param.kind == "object":
			continue
		at = arguments[param.name]
		source = f"arguments + {at}" if at else "arguments"
		if param.kind == "span":
			element = (SCALARS[param.type][0] if param.type in SCALARS else "::Shalltear::" + param.type if param.type in VALUES else
					   cpp_type_of("struct", param.type, catalog))
			items = ("" if param.out else "const ") + element
			out.append(f"{inner}const std::span<{items}> {param.name}(reinterpret_cast<{items}*>(static_cast<uintptr_t>(arguments[{at}])), "
					   f"static_cast<size_t>(arguments[{at + 1}]));")
		elif param.kind == "list":
			element_kind, _ = classify(param.type, catalog)
			if element_kind == "object":
				out.append(f"{inner}const auto {param.name} = Slots::Objects<{catalog.objects[param.type]}>({source});")
			elif element_kind == "string":
				out.append(f"{inner}const auto {param.name} = Slots::Views({source});")
			elif element_kind == "native":
				cpp = catalog.natives[param.type].cpp
				out.append(f"{inner}const std::span<{cpp}* const> {param.name}(reinterpret_cast<{cpp}* const*>(static_cast<uintptr_t>(arguments[{at}])), "
						   f"static_cast<size_t>(arguments[{at + 1}]));")
			else:
				element = cpp_type_of(element_kind, param.type, catalog)
				out.append(f"{inner}const std::span<const {element}> {param.name}(reinterpret_cast<const {element}*>(static_cast<uintptr_t>(arguments[{at}])), "
						   f"static_cast<size_t>(arguments[{at + 1}]));")
		elif param.kind == "callback":
			out += callback_thunk(param, catalog, inner, at)
		elif param.kind == "native" and param.shared == "unique":
			out.append(f"{inner}std::unique_ptr<{catalog.natives[param.type].cpp}> {param.name}(reinterpret_cast<{catalog.natives[param.type].cpp}*>("
					   f"static_cast<uintptr_t>(arguments[{at}])));")
		elif param.kind == "native" and param.shared:
			out.append(f"{inner}const std::shared_ptr<{catalog.natives[param.type].cpp}> {param.name} = Slots::Shared<{catalog.natives[param.type].cpp}>(arguments[{at}]);")
		elif param.kind == "native":
			out.append(f"{inner}{catalog.natives[param.type].cpp}* const {param.name} = {cpp_slot_read(param.kind, param.type, catalog, 'arguments', at)};")
		elif param.kind == "struct" and param.implicit:
			out.append(f"{inner}{cpp_type_of(param.kind, param.type, catalog)} selfValue = {cpp_slot_read(param.kind, param.type, catalog, 'arguments', at)};")
			out.append(f"{inner}{'' if function.mutates else 'const '}auto* const self = &selfValue;")
		else:
			out.append(f"{inner}const {cpp_type_of(param.kind, param.type, catalog)} {param.name} = {cpp_slot_read(param.kind, param.type, catalog, 'arguments', at)};")
	if function.return_kind == "void":
		out.append(f"{inner}{function.cpp};")
	else:
		if function.shared:
			out.append(f"{inner}results[{results['']}] = Slots::KeepShared<{catalog.natives[function.returns].cpp}>({function.cpp});")
		else:
			out.append(f"{inner}{cpp_slot_write(function.return_kind, function.returns, catalog, 'results', results[''], function.cpp, function.owns)}")
	for param in function.params:
		if param.out and param.kind != "span":
			out.append(f"{inner}{cpp_slot_write(param.kind, param.type, catalog, 'results', results[param.name], param.name, boxed(param, catalog))}")
	if function.mutates:
		out.append(f"{inner}Slots::StructOut<{cpp_type_of('struct', function.params[0].type, catalog)}>(arguments[0], selfValue);")
	out.append(f"{tabs}\t}});")
	if flushes:
		out += [f"{tabs}\tManagedTypes::FlushDirty();", f"{tabs}\treturn status;"]
	out.append(f"{tabs}}}")
	return out


def cs_list_type(type_name, catalog):
	kind, _ = classify(type_name, catalog)
	return "string" if kind == "string" else cs_api_type(kind, type_name)


def cs_slot_api_type(kind, type_name, catalog):
	if kind == "string":
		return "string"
	if kind == "list":
		return cs_list_type(type_name, catalog) + "[]"
	return cs_api_type(kind, type_name)


def cs_slot_read(kind, type_name, catalog, offset, nullable=True, owns=False, owner="null"):
	source = f"slots + {offset}" if offset else "slots"
	cell = f"slots[{offset}]"
	if kind == "scalar":
		if type_name == "bool":
			return f"{cell} != 0"
		if type_name == "f32":
			return f"BitConverter.UInt32BitsToSingle((uint){cell})"
		if type_name == "f64":
			return f"BitConverter.UInt64BitsToDouble({cell})"
		return f"({SCALARS[type_name][2]}){cell}"
	if kind == "enum":
		declared = catalog.enums[type_name]
		return f"new {type_name}({cell})" if declared.handle else f"({type_name})({SCALARS[declared.underlying][2]}){cell}"
	if kind == "value":
		return f"SlotValues.{type_name}({source})"
	if kind == "string":
		return f"SlotValues.Text({source})"
	if kind == "native":
		return (f"NativeObject.Wrap({cell}, {'true' if owns else 'false'}, static (pointer, owned) => new {type_name}(pointer, owned), "
				f"{'null' if owns else owner}){'' if nullable else '!'}")
	if kind == "list":
		element_kind, _ = classify(type_name, catalog)
		if element_kind == "object":
			return f"SlotValues.Objects<{type_name}>({source})"
		if element_kind == "string":
			return f"SlotValues.Texts({source})"
		if element_kind == "native":
			return (f"SlotValues.Natives({source}, static (pointer, owned) => new {type_name}(pointer, owned), {'true' if owns else 'false'}, "
					f"{'null' if owns else owner})")
		return f"SlotValues.Array<{cs_api_type(element_kind, type_name)}>({source})"
	wrap = WRAPPERS.get(type_name, f"ObjectCache.Find<{type_name}>")
	return f"{wrap}({cell}){'' if nullable else '!'}"


def cs_slot_call(area, function, setter):
	catalog = function.catalog
	arguments, argument_count, results, result_count = slot_layout(function)
	member = "member" if function.relay else f'"{area.class_name}.{function.member}"'
	lines = []
	if not function.any_thread:
		lines += ["if (Bridge.OffMainThread) {", f"\tBridge.ThrowOffMainThread({member});", "}"]
	puts, pinned, after = [], [], []
	for param in function.params:
		name = "value" if setter and not param.implicit else param.name
		if param.out and param.kind != "span":
			continue
		at = arguments[param.name]
		if param.kind == "scalar":
			if param.type == "bool":
				puts.append(f"slots[{at}] = {name} ? 1UL : 0UL;")
			elif param.type == "f32":
				puts.append(f"slots[{at}] = BitConverter.SingleToUInt32Bits({name});")
			elif param.type == "f64":
				puts.append(f"slots[{at}] = BitConverter.DoubleToUInt64Bits({name});")
			else:
				puts.append(f"slots[{at}] = (ulong){'(long)' if param.type in SIGNED else ''}{name};")
		elif param.kind == "enum":
			declared = catalog.enums[param.type]
			if declared.handle:
				puts.append(f"slots[{at}] = {name}.{declared.bits};")
			else:
				puts.append(f"slots[{at}] = (ulong){'(long)' if declared.underlying in SIGNED else ''}({SCALARS[declared.underlying][2]}){name};")
		elif param.kind == "value":
			puts.append(f"SlotValues.Put(slots + {at}, {name});")
		elif param.kind == "string":
			lines.append(f"using UTF8Scratch {name}Text = new({name}, stackalloc byte[UTF8Scratch.STACK_BYTES]);")
			puts += [f"slots[{at}] = (ulong){name}Text.Text.ptr;", f"slots[{at + 1}] = (ulong){name}Text.Text.length;"]
		elif param.kind == "object":
			if param.implicit:
				puts.append(f"slots[{at}] = _id;")
			elif param.optional:
				puts.append(f"slots[{at}] = {name} is null ? 0UL : {name}._id;")
			else:
				lines.append(f"ArgumentNullException.ThrowIfNull({name});")
				puts.append(f"slots[{at}] = {name}._id;")
		elif param.kind == "native":
			if param.implicit:
				puts.append(f"slots[{at}] = Pointer;")
			elif param.shared:
				given = f"Give({member})" if param.shared == "unique" else f"Share({'true' if param.shared == 'take' else 'false'})"
				if not param.optional:
					lines.append(f"ArgumentNullException.ThrowIfNull({name});")
				puts.append(f"slots[{at}] = {name} is null ? 0UL : {name}.{given};" if param.optional else f"slots[{at}] = {name}.{given};")
			elif param.optional:
				puts.append(f"slots[{at}] = {name} is null ? 0UL : {name}.Pointer;")
			else:
				lines.append(f"ArgumentNullException.ThrowIfNull({name});")
				puts.append(f"slots[{at}] = {name}.Pointer;")
		elif param.kind == "struct" and param.implicit:
			lines.append(f"{param.type} selfCopy = this;")
			puts.append(f"slots[{at}] = (ulong)&selfCopy;")
		elif param.kind == "struct":
			lines.append(f"{param.type} {name}Copy = {name};")
			puts.append(f"slots[{at}] = (ulong)&{name}Copy;")
		elif param.kind == "callback":
			if param.optional:
				puts.append(f"slots[{at}] = SlotCallbacks.Keep({name} is null ? null : {callback_name(function, param)}({name}));")
			else:
				lines.append(f"ArgumentNullException.ThrowIfNull({name});")
				puts.append(f"slots[{at}] = SlotCallbacks.Keep({callback_name(function, param)}({name}));")
		elif param.kind == "span":
			pinned.append(f"fixed ({span_element(param, catalog, True)}* {name}Data = {name})")
			after += [f"slots[{at}] = (ulong){name}Data;", f"slots[{at + 1}] = (ulong){name}.Length;"]
		else:
			element_kind, _ = classify(param.type, catalog)
			if element_kind == "object":
				lines.append(f"using SlotList {name}List = SlotList.OfObjects({name});")
				puts += [f"slots[{at}] = (ulong){name}List.Data;", f"slots[{at + 1}] = (ulong){name}.Length;"]
			elif element_kind == "native":
				lines.append(f"using SlotList {name}List = SlotList.OfNatives({name});")
				puts += [f"slots[{at}] = (ulong){name}List.Data;", f"slots[{at + 1}] = (ulong){name}.Length;"]
			elif element_kind == "string":
				lines.append(f"using SlotList {name}List = SlotList.OfTexts({name});")
				puts += [f"slots[{at}] = (ulong){name}List.Data;", f"slots[{at + 1}] = (ulong){name}.Length;"]
			else:
				pinned.append(f"fixed ({cs_api_type(element_kind, param.type)}* {name}Data = {name})")
				after += [f"slots[{at}] = (ulong){name}Data;", f"slots[{at + 1}] = (ulong){name}.Length;"]
	total = max(1, argument_count + result_count)
	lines.append(f"ulong* slots = stackalloc ulong[{total}];")
	base = f"slots + {argument_count}" if argument_count else "slots"
	body = []
	if function.return_kind == "struct":
		body += [f"{function.returns} result = default;", f"slots[{argument_count + results['']}] = (ulong)&result;"]
	for param in function.params:
		if param.out and param.kind == "struct":
			body += [f"{param.name} = default;", f"{param.type} {param.name}Out = default;", f"slots[{argument_count + results[param.name]}] = (ulong)&{param.name}Out;"]
	owner = "this" if area.instance in catalog.natives and not function.static else "null"
	body += after
	dropped = [f"\tSlotCallbacks.Drop(slots[{arguments[param.name]}]);" for param in function.params if param.kind == "callback"]
	body += [f"int status = {area.set.holder}.table.{function.table_member}(slots, {base});", "if (status != Bridge.OK) {"] + dropped + [
		f"\tthrow Bridge.Failure(status, {member});", "}"]
	for param in function.params:
		if not param.out or param.kind == "span":
			continue
		at = argument_count + results[param.name]
		if param.kind == "struct":
			body.append(f"{param.name} = {param.name}Out;")
		else:
			body.append(f"{param.name} = {cs_slot_read(param.kind, param.type, catalog, at, owns=boxed(param, catalog), owner=owner)};")
	if function.mutates:
		body.append("this = selfCopy;")
	if function.return_kind == "struct":
		body.append("return result;")
	elif function.return_kind != "void":
		at = argument_count + results[""]
		if function.shared:
			body.append(f"return NativeObject.WrapShared(slots[{at}], static (pointer, owned) => new {function.returns}(pointer, owned))"
						f"{'' if function.nullable else '!'};")
		else:
			body.append(f"return {cs_slot_read(function.return_kind, function.returns, catalog, at, function.nullable, function.owns or function.adopts, owner)};")
	lines += puts
	if pinned:
		lines += pinned[:-1] + [pinned[-1] + " {"] + ["\t" + line for line in body] + ["}"]
	else:
		lines += body
	return lines


def cs_slot_parameters(function):
	catalog = function.catalog
	parts = []
	listed = explicit(function)
	for index, param in enumerate(listed):
		if param.out and param.kind != "span":
			nullable = "?" if param.kind in ("object", "native") else ""
			parts.append(f"out {cs_slot_api_type(param.kind, param.type, catalog)}{nullable} {param.name}")
		elif param.kind == "string":
			parts.append(f"string {param.name}")
		elif param.kind == "span":
			parts.append(f"{'Span' if param.out else 'ReadOnlySpan'}<{span_element(param, catalog, 'api')}> {param.name}")
		elif param.kind == "list":
			parts.append(f"ReadOnlySpan<{cs_list_type(param.type, catalog)}> {param.name}")
		elif param.kind == "struct":
			parts.append(f"in {param.type} {param.name}")
		elif param.kind == "callback":
			parts.append(f"{cs_delegate(param, catalog)}{'?' if param.optional else ''} {param.name}")
		elif param.kind in ("object", "native"):
			trailing = not function.relay and all((later.kind in ("object", "native") and later.optional) or later.default is not None for later in listed[index:])
			parts.append(f"{param.type}? {param.name}{' = null' if trailing else ''}" if param.optional else f"{param.type} {param.name}")
		else:
			parts.append(f"{cs_api_type(param.kind, param.type)} {param.name}{'' if param.default is None else ' = ' + param.default}")
	if function.relay:
		parts.append("string member")
	return ", ".join(parts)


def render_native(declared, area):
	out = []
	if declared.doc:
		out.append(f"/// <summary>{xml_text(declared.doc)}</summary>")
	delete = f"owned ? {area.set.holder}.table.{camel_case(area.name)}{declared.name}Delete : null" if declared.owned else "null"
	access = "internal" if area.test or area.internal else "public"
	out += [f"{access} sealed unsafe partial class {declared.name} : NativeObject {{", f"\tinternal {declared.name}(nint pointer, bool owned) : base(pointer, {delete}) {{}}",
			"", "\t/// <summary>Wrapper of the C++ object at an address (not owned, null at 0).</summary>",
			f"\tpublic static {declared.name}? FromAddress(ulong address) {{", f"\t\treturn address == 0 ? null : new {declared.name}((nint)address, false);", "\t}"]
	if declared.create:
		out += ["", f"\tpublic {declared.name}() : this(Create(), true) {{}}", "", "\tstatic nint Create() {", "\t\tulong* slots = stackalloc ulong[1];",
				f"\t\tint status = {area.set.holder}.table.{camel_case(area.name)}{declared.name}New(slots, slots);", "\t\tif (status != Bridge.OK) {",
				f'\t\t\tthrow Bridge.Failure(status, "{declared.name}");', "\t\t}", "\t\treturn (nint)slots[0];", "\t}"]
	out += ["}", ""]
	return out


def cs_parameters(function):
	if function.slots:
		return cs_slot_parameters(function)
	parts = []
	listed = explicit(function)
	for index, param in enumerate(listed):
		if param.kind == "string":
			parts.append(f"string {param.name}")
		elif param.kind == "span":
			parts.append(f"{'Span' if param.out else 'ReadOnlySpan'}<{span_element(param, function.catalog, 'api')}> {param.name}")
		elif param.kind == "object":
			trailing = not function.relay and all((later.kind == "object" and later.optional) or later.default is not None for later in listed[index:])
			parts.append(f"{param.type}? {param.name}{' = null' if trailing else ''}" if param.optional else f"{param.type} {param.name}")
		else:
			parts.append(f"{cs_api_type(param.kind, param.type)} {param.name}{'' if param.default is None else ' = ' + param.default}")
	if function.relay:
		parts.append("string member")
	return ", ".join(parts)


def render_handle(declared):
	name, bits = declared.name, declared.bits
	out = ([f"/// <summary>{xml_text(declared.doc)}</summary>"] if declared.doc else []) + [f"public readonly partial struct {name} : IEquatable<{name}> {{"]
	if declared.value:
		out += [f"\t/// <summary>{xml_text(declared.value[1])}</summary>", f"\tpublic readonly ulong {bits};", "",
				f"\t/// <summary>{xml_text(declared.value[1])}</summary>", f"\tpublic {name}(ulong {bits}) {{", f"\t\tthis.{bits} = {bits};", "\t}"]
	else:
		out += [f"\tinternal readonly ulong {bits};", "", f"\tinternal {name}(ulong bits) {{", f"\t\t{bits} = bits;", "\t}"]
	out += ["", "\t/// <inheritdoc/>", f"\tpublic bool Equals({name} other) {{", f"\t\treturn {bits} == other.{bits};", "\t}", "",
			"\t/// <inheritdoc/>", "\tpublic override bool Equals(object? other) {", f"\t\treturn other is {name} value && {bits} == value.{bits};", "\t}", "",
			"\t/// <inheritdoc/>", "\tpublic override int GetHashCode() {", f"\t\treturn {bits}.GetHashCode();", "\t}", "",
			"\t/// <summary>Same value.</summary>", f"\tpublic static bool operator ==({name} left, {name} right) {{", f"\t\treturn left.{bits} == right.{bits};",
			"\t}", "", "\t/// <summary>Opposite of ==.</summary>", f"\tpublic static bool operator !=({name} left, {name} right) {{",
			f"\t\treturn left.{bits} != right.{bits};", "\t}", "}", ""]
	return out


def render_managed_types(area):
	out = []
	access = "internal" if area.test or area.internal else "public"
	for declared in area.enums:
		if declared.handle:
			out += render_handle(declared)
			continue
		out += ([f"/// <summary>{xml_text(declared.doc)}</summary>"] if declared.doc else []) + (["[Flags]"] if declared.flags else [])
		out.append(f"{access} enum {declared.name} : {SCALARS[declared.underlying][2]} {{")
		for name, value, doc in declared.values:
			out += ([f"\t/// <summary>{xml_text(doc)}</summary>"] if doc else []) + [f"\t{name} = {value},"]
		out += ["}", ""]
	for declared in area.structs:
		if declared.external:
			continue
		if declared.cpp:
			out += ([f"/// <summary>{xml_text(declared.doc)}</summary>"] if declared.doc else []) + [
				f"[System.Runtime.InteropServices.StructLayout(System.Runtime.InteropServices.LayoutKind.Explicit, Size = {declared.size})]",
				f"{access} partial struct {declared.name} {{"]
			for field in declared.fields:
				out += ([f"\t/// <summary>{xml_text(field.doc)}</summary>"] if field.doc else []) + [
					f"\t[System.Runtime.InteropServices.FieldOffset({field.offset})]", f"\tpublic {cs_api_type(field.kind, field.type)} {field.name};"]
			out += ["}", ""]
			continue
		out += [f"/// <summary>{xml_text(declared.doc)}</summary>",
				"[System.Runtime.InteropServices.StructLayout(System.Runtime.InteropServices.LayoutKind.Sequential)]",
				f"{access} partial struct {declared.name} {{"]
		for field in declared.fields:
			if field.internal:
				out.append(f"\tinternal {cs_api_type(field.kind, field.type)} _{field.name};")
			else:
				out += [f"\t/// <summary>{xml_text(field.doc)}</summary>", f"\tpublic {cs_api_type(field.kind, field.type)} {field.name};"]
		out += ["}", ""]
	for declared in area.types:
		if declared.external:
			continue
		out += ([f"/// <summary>{xml_text(declared.doc)}</summary>"] if declared.doc else []) + ["[EngineType(ENGINE_TYPE)]"]
		constant = f'\tinternal {"" if declared.base in BASES else "new "}const string ENGINE_TYPE = "{declared.engine}";'
		if declared.abstract:
			out += [f"public abstract partial class {declared.name} : {declared.base} {{", constant, "", f"\tprivate protected {declared.name}() {{}}", "}", "",
					f"internal sealed class Opaque{declared.name} : {declared.name} {{", f"\tinternal Opaque{declared.name}(ulong id) {{", "\t\t_id = id;", "\t}", "}", ""]
		else:
			out += [f"public sealed partial class {declared.name} : {declared.base} {{", constant,
					"", f"\tinternal {declared.name}(ulong id) {{", "\t\t_id = id;", "\t}", "}", ""]
	return out


def render_managed_wrappers(areas):
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable", "", "namespace Shalltear.Interop;", "",
		   "internal static partial class ObjectCache {", "\tstatic void WrapGenerated() {"]
	for area in areas:
		out += wrapper_lines(area, "")
	out += ["\t}", "}", ""]
	return "\n".join(out)


def render_managed_area(area):
	access = "internal" if area.test or area.internal else "public"
	static = "" if area.instance else "static "
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable"] + (["#pragma warning disable CS1591"] if area.slots else []) + ["", "using System;", ""]
	if area.namespace != "Shalltear.Interop":
		out += ["using Shalltear.Interop;", ""]
	out += [f"namespace {area.namespace};", ""]
	out += render_managed_types(area)
	for declared in area.natives:
		out += render_native(declared, area)
	bare = not area.instance and not area.constants and all(function.hidden for function in area.functions)
	if bare and (area.types or area.enums or area.structs or area.natives):
		return "\n".join(out)
	if area.doc:
		out.append(f"/// <summary>{xml_text(area.doc)}</summary>")
	kind = "struct" if area.instance in area.catalog.structs else "class"
	out.append(f"{access} {static}unsafe partial {kind} {area.class_name} {{")

	emitted = set()
	blocks = []
	if area.constants:
		block = []
		for declared in area.constants:
			block += ([f"\t/// <summary>{xml_text(declared.doc)}</summary>"] if declared.doc else []) + [
				f"\t{access} const {'string' if declared.type == 'string' else SCALARS[declared.type][2]} {declared.name} = {constant_literal(declared)};"]
		blocks.append(block)
	for function in area.functions:
		key = function.id if function.kind == "method" else function.member
		if key in emitted or function.hidden:
			continue
		emitted.add(key)
		block = []
		if function.kind == "method":
			if function.doc:
				block.append(f"\t/// <summary>{xml_text(function.doc)}</summary>")
			if function.conditional:
				block.append(f'\t[System.Diagnostics.Conditional("{function.conditional}")]')
			if any(param.kind == "string" for param in function.params):
				block.append("\t[System.Runtime.CompilerServices.SkipLocalsInit]")
			shared = "static " if function.static else static
			block.append(f"\t{function.access or access} {shared}{cs_return_type(function)} {function.member}({cs_parameters(function)}) {{")
			block += ["\t\t" + line for line in cs_call(area, function, False)]
			block.append("\t}")
			for param in function.params:
				if param.kind == "callback":
					block += [""] + callback_helper(function, param)
		else:
			group = [other for other in area.functions if other.member == function.member and not other.hidden]
			getter = next((other for other in group if other.kind == "getter"), None)
			setter = next((other for other in group if other.kind == "setter"), None)
			doc = (getter.doc if getter else "") or (setter.doc if setter else "")
			if doc:
				block.append(f"\t/// <summary>{xml_text(doc)}</summary>")
			value = None if getter else explicit(setter)[0]
			if getter:
				type_name = cs_return_type(getter)
			elif value.kind in ("object", "native"):
				type_name = value.type + ("?" if value.optional else "")
			elif value.kind == "list":
				type_name = "ReadOnlySpan<" + cs_list_type(value.type, function.catalog) + ">"
			else:
				type_name = cs_api_type(value.kind, value.type)
			shared = "static " if function.static else static
			block.append(f"\t{function.access or access} {shared}{type_name} {function.member} {{")
			if getter:
				block += ["\t\tget {"] + ["\t\t\t" + line for line in cs_call(area, getter, False)] + ["\t\t}"]
			if setter:
				block += ["\t\tset {"] + ["\t\t\t" + line for line in cs_call(area, setter, True)] + ["\t\t}"]
			block.append("\t}")
		blocks.append(block)
	for index, block in enumerate(blocks):
		out += block + ([""] if index + 1 < len(blocks) else [])
	out += ["}", ""]
	return "\n".join(out)


def render_sets(sets, digest):
	files = {}
	for binding_set in sets:
		areas = binding_set.areas
		files[binding_set.native / binding_set.header] = render_native_header(areas, digest)
		files[binding_set.native / f"{binding_set.name}Bindings.generated.cpp"] = render_native_table(areas)
		if binding_set.name:
			files[binding_set.managed / f"{binding_set.name}Bindings.g.cs"] = render_package_table(binding_set)
		else:
			files[binding_set.managed / "Bindings.g.cs"] = render_managed_table(areas)
			files[binding_set.managed / "Wrappers.g.cs"] = render_managed_wrappers(areas)
		for area in areas:
			files[binding_set.native / f"{area.name}.generated.cpp"] = render_native_area(area)
			files[binding_set.managed / f"{area.name}.g.cs"] = render_managed_area(area)
	return files


def find_stale(files, sets):
	stale = [path for path, text in files.items() if not path.exists() or path.read_bytes() != text.encode("utf-8")]
	for binding_set in sets:
		for directory, pattern in ((binding_set.native, "*.generated.*"), (binding_set.managed, "*.g.cs")):
			stale += [path for path in sorted(directory.glob(pattern)) if path not in files]
	return stale


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true", help="fail if the committed output differs (don't rewrite it)")
	args = parser.parse_args()

	try:
		sets = load_sets(find_sets(ROOT))
	except SchemaError as error:
		sys.exit(str(error))
	areas = [area for binding_set in sets for area in binding_set.areas]
	files = render_sets(sets, sets_digest(sets, Path(__file__).resolve()))
	stale = find_stale(files, sets)
	if args.check:
		if stale:
			sys.exit("stale generated C# bindings: " + ", ".join(path.relative_to(ROOT).as_posix() for path in stale) +
					 "\nRun: python Scripts/generate_csharp_bindings.py")
		print(f"C# bindings up to date ({sum(len(area.functions) for area in areas)} function(s) in {len(areas)} area(s))")
		return

	for path in stale:
		if path in files:
			path.parent.mkdir(parents=True, exist_ok=True)
			path.write_bytes(files[path].encode("utf-8"))
		else:
			path.unlink()
		print(f"  -> {path.relative_to(ROOT).as_posix()}")
	print(f"{sum(len(area.functions) for area in areas)} function(s) in {len(areas)} area(s), {len(stale)} file(s) written")


if __name__ == "__main__":
	main()
