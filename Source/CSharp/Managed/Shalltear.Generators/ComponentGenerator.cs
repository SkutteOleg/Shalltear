using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Shalltear.Generators;

[Generator]
public sealed class ComponentGenerator : IIncrementalGenerator {
	const string BEHAVIOR = "Shalltear.Behavior";

	// bit order must match SLT_HOOK_* in ScriptBridge.h
	static readonly string[] _hooks = { "OnAttach", "OnDetach", "OnEnable", "OnDisable", "OnDestroy", "OnUpdate", "OnFixedUpdate", "OnLateUpdate" };

	static readonly SymbolDisplayFormat _plain =
		SymbolDisplayFormat.FullyQualifiedFormat.WithGlobalNamespaceStyle(SymbolDisplayGlobalNamespaceStyle.Omitted);

	public void Initialize(IncrementalGeneratorInitializationContext context) {
		IncrementalValuesProvider<(string Name, string Qualified, string Parent, bool IsAbstract, uint HookMask, int Depth)> classes =
			context.SyntaxProvider.CreateSyntaxProvider(
				static (node, _) => node is ClassDeclarationSyntax declaration && declaration.BaseList != null,
				static (syntax, cancel) => Describe(syntax.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)syntax.Node, cancel) as INamedTypeSymbol));
		IncrementalValuesProvider<(string Name, string Qualified, string Parent, bool IsAbstract, uint HookMask, int Depth)> components =
			classes.Where(static component => component.Name != null);
		context.RegisterSourceOutput(components.Collect(), static (output, found) => {
			if (!found.IsDefaultOrEmpty) {
				output.AddSource("TypeTable.g.cs", SourceText.From(Render(found), Encoding.UTF8));
			}
		});
	}

	static bool IsRegistered(INamedTypeSymbol type) {
		return !type.IsGenericType && type.ContainingType == null && !type.IsStatic && !type.IsFileLocal;
	}

	static (string Name, string Qualified, string Parent, bool IsAbstract, uint HookMask, int Depth) Describe(INamedTypeSymbol? type) {
		if (type == null || !IsRegistered(type)) {
			return default;
		}
		uint hookMask = 0;
		string parent = "";
		int depth = 0;
		bool behavior = false;
		for (INamedTypeSymbol? level = type; level != null; level = level.BaseType) {
			if (level.ToDisplayString(_plain) == BEHAVIOR) {
				behavior = true;
				break;
			}
			for (int hook = 0; hook < _hooks.Length; ++hook) {
				if (level.GetMembers(_hooks[hook]).OfType<IMethodSymbol>().Any(static method => method.IsOverride && method.Parameters.Length == 0)) {
					hookMask |= 1u << hook;
				}
			}
			if (!SymbolEqualityComparer.Default.Equals(level, type) && IsRegistered(level)) {
				if (depth == 0) {
					parent = level.ToDisplayString(_plain);
				}
				++depth;
			}
		}
		if (!behavior) {
			return default;
		}
		return (type.ToDisplayString(_plain), type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), parent, type.IsAbstract, hookMask, depth);
	}

	static ulong Hash(string text) {
		ulong hash = 0xcbf29ce484222325UL;
		foreach (byte value in Encoding.UTF8.GetBytes(text)) {
			hash ^= value;
			hash *= 0x00000100000001b3UL;
		}
		return hash;
	}

	static string Hex(ulong value) {
		return "0x" + value.ToString("x16", CultureInfo.InvariantCulture) + "UL";
	}

	static string Render(ImmutableArray<(string Name, string Qualified, string Parent, bool IsAbstract, uint HookMask, int Depth)> found) {
		StringBuilder text = new();
		text.Append("// <auto-generated/>\n");
		text.Append("#pragma warning disable CA2255\n");
		text.Append("namespace Shalltear.Generated;\n\n");
		text.Append("static class TypeTable {\n");
		text.Append("\tstatic bool _registered;\n\n");
		text.Append("\t[global::System.Runtime.CompilerServices.ModuleInitializer]\n");
		text.Append("\tinternal static void Register() {\n");
		text.Append("\t\tif (_registered || !global::Shalltear.Interop.ScriptTypes.IsAttached) {\n\t\t\treturn;\n\t\t}\n");
		text.Append("\t\t_registered = true;\n");
		HashSet<string> seen = new(StringComparer.Ordinal);
		var ordered = found.OrderBy(static component => component.Depth).ThenBy(static component => component.Name, StringComparer.Ordinal);
		foreach ((string name, string qualified, string parent, bool isAbstract, uint hookMask, int _) in ordered) {
			if (!seen.Add(name)) {
				continue;
			}
			string[] arguments = {
				SymbolDisplay.FormatLiteral(name, true),
				Hex(Hash(name)),
				parent.Length == 0 ? "0UL" : Hex(Hash(parent)),
				isAbstract ? "true" : "false",
				hookMask.ToString(CultureInfo.InvariantCulture) + "u",
				((hookMask >> 5) & 7u).ToString(CultureInfo.InvariantCulture) + "u",
				isAbstract ? "null" : "static () => new " + qualified + "()",
			};
			text.Append("\t\tglobal::Shalltear.Interop.ScriptTypes.Register(").Append(string.Join(", ", arguments)).Append(");\n");
		}
		text.Append("\t}\n}\n");
		return text.ToString();
	}
}
