"""Writes the C# bridge's binding tables from Source/CSharp/Bindings/*.json
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BINDINGS = ROOT / "Source" / "CSharp" / "Bindings"
NATIVE = ROOT / "Source" / "CSharp" / "Private" / "Generated"
MANAGED = ROOT / "Source" / "CSharp" / "Managed" / "Shalltear.Runtime" / "Generated"
BANNER = "generated by Scripts/generate_csharp_bindings.py. Do not edit manually"

SCALARS = {
	"bool": ("uint8_t", "byte", "bool"),
	"i32": ("int32_t", "int", "int"),
	"u32": ("uint32_t", "uint", "uint"),
	"i64": ("int64_t", "long", "long"),
	"u64": ("uint64_t", "ulong", "ulong"),
	"f32": ("float", "float", "float"),
	"f64": ("double", "double", "double"),
}
VALUES = {
	"Vec2": ("x", "y"),
	"Vec3": ("x", "y", "z"),
	"Vec4": ("x", "y", "z", "w"),
	"Quat": ("x", "y", "z", "w"),
	"Color": ("r", "g", "b", "a"),
}
# 16 byte aligned in engine, 4 in C#
WIDE = ("Vec4", "Quat")
VALUE_HEADERS = ("Shalltear/Core/Math/Color.h", "Shalltear/Core/Math/Quat.h", "Shalltear/Core/Math/Vector.h")
# bump when a type's C signature changes
LOWERING = 1
TYPE_LIST = ", ".join(list(SCALARS) + list(VALUES)) + ", string, span<T>"
IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9]*\Z")
CLASS_NAME = re.compile(r"[A-Za-z][A-Za-z0-9]*(\.[A-Za-z][A-Za-z0-9]*)+\Z")
SPAN = re.compile(r"span<([A-Za-z0-9]+)>\Z")
AREA_KEYS = {"area", "include", "class", "doc", "test", "functions"}
FUNCTION_KEYS = {"id", "cpp", "returns", "params", "leaf", "thread", "csharp", "doc"}
PARAM_KEYS = {"name", "type", "out"}
CSHARP_KEYS = {"member", "kind", "conditional"}
FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3


class SchemaError(Exception):
	pass


class Param:
	def __init__(self, name, kind, type_name, out):
		self.name = name
		self.kind = kind
		self.type = type_name
		self.out = out


class Function:
	pass


class Area:
	pass


def fnv1a(data, seed=FNV_OFFSET):
	value = seed
	for byte in data:
		value = ((value ^ byte) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
	return value


def classify(type_name):
	if type_name == "void":
		return "void", type_name
	if type_name in SCALARS:
		return "scalar", type_name
	if type_name in VALUES:
		return "value", type_name
	if type_name == "string":
		return "string", type_name
	match = SPAN.match(type_name) if isinstance(type_name, str) else None
	if match and match.group(1) in SCALARS and match.group(1) != "bool":
		return "span", match.group(1)
	return None, type_name


def check_keys(found, allowed, required, path, where):
	unknown = sorted(set(found) - allowed)
	if unknown:
		raise SchemaError(f"{path.name}: {where}: unknown key '{unknown[0]}'. Use {', '.join(sorted(allowed))}")
	missing = sorted(required - set(found))
	if missing:
		raise SchemaError(f"{path.name}: {where}: '{missing[0]}' is missing")


def parse_function(raw, area, path):
	where = raw.get("id", "function") if isinstance(raw, dict) else "function"
	if not isinstance(raw, dict):
		raise SchemaError(f"{path.name}: {where}: function must be an object")
	check_keys(raw, FUNCTION_KEYS, {"id", "cpp", "returns", "params", "csharp"}, path, where)
	function = Function()
	function.id = raw["id"]
	if not isinstance(function.id, str) or not IDENTIFIER.match(function.id):
		raise SchemaError(f"{path.name}: {where}: 'id' must be letters/digits")
	function.cpp = raw["cpp"]
	function.leaf = raw.get("leaf", False)
	function.guarded = not function.leaf
	function.any_thread = raw.get("thread", "main") == "any"
	if raw.get("thread", "main") not in ("main", "any"):
		raise SchemaError(f"{path.name}: {where}: 'thread' is '{raw['thread']}'. Use main/any")
	function.doc = raw.get("doc", "")

	function.return_kind, function.returns = classify(raw["returns"])
	if function.return_kind not in ("void", "scalar", "value"):
		raise SchemaError(f"{path.name}: {where}: can't return '{raw['returns']}'. Use void, {', '.join(list(SCALARS) + list(VALUES))}")

	function.params = []
	for entry in raw["params"]:
		if not isinstance(entry, dict):
			raise SchemaError(f"{path.name}: {where}: parameter must be an object")
		check_keys(entry, PARAM_KEYS, {"name", "type"}, path, where)
		kind, type_name = classify(entry["type"])
		if kind in (None, "void"):
			raise SchemaError(f"{path.name}: {where}: unknown type '{entry['type']}'. Use {TYPE_LIST}")
		if entry.get("out", False) and kind != "span":
			raise SchemaError(f"{path.name}: {where}: 'out' is for a span, '{entry['name']}' is {entry['type']}")
		if not isinstance(entry["name"], str) or not IDENTIFIER.match(entry["name"]):
			raise SchemaError(f"{path.name}: {where}: parameter name must be letters/digits")
		function.params.append(Param(entry["name"], kind, type_name, entry.get("out", False)))

	csharp = raw["csharp"]
	check_keys(csharp, CSHARP_KEYS, {"member", "kind"}, path, where)
	function.member = csharp["member"]
	function.kind = csharp["kind"]
	function.conditional = csharp.get("conditional", "")
	if function.kind not in ("getter", "setter", "method"):
		raise SchemaError(f"{path.name}: {where}: 'kind' is '{function.kind}'. Use getter/setter/method")
	if function.kind == "getter" and (function.params or function.return_kind == "void"):
		raise SchemaError(f"{path.name}: {where}: getter must take nothing + return a value")
	if function.kind == "setter" and (len(function.params) != 1 or function.return_kind != "void"):
		raise SchemaError(f"{path.name}: {where}: setter must take 1 parameter + return void")
	if function.conditional and (function.kind != "method" or function.return_kind != "void"):
		raise SchemaError(f"{path.name}: {where}: 'conditional' needs a method returning void")
	if function.member == area.class_name:
		raise SchemaError(f"{path.name}: {where}: member '{function.member}' has the class name. Rename the member")
	if not area.test and not function.doc and function.kind != "setter":
		raise SchemaError(f"{path.name}: {where}: 'doc' is missing")
	function.table_member = area.name[0].lower() + area.name[1:] + function.id
	function.thunk = area.name + function.id
	return function


def parse_area(path):
	try:
		raw = json.loads(path.read_text(encoding="utf-8"))
	except json.JSONDecodeError as error:
		raise SchemaError(f"{path.name}: not JSON ({error})") from error
	if not isinstance(raw, dict):
		raise SchemaError(f"{path.name}: file must hold an object")
	check_keys(raw, AREA_KEYS, {"area", "include", "class", "functions"}, path, "file")
	area = Area()
	area.name = raw["area"]
	if area.name != path.stem or not IDENTIFIER.match(area.name):
		raise SchemaError(f"{path.name}: 'area' is '{area.name}'. Name it like the file ({path.stem})")
	area.include = raw["include"]
	if not isinstance(raw["class"], str) or not CLASS_NAME.match(raw["class"]):
		raise SchemaError(f"{path.name}: 'class' must be a namespace + name (Shalltear.Time)")
	area.namespace, area.class_name = raw["class"].rsplit(".", 1)
	area.test = raw.get("test", False)
	area.doc = raw.get("doc", "")
	if not area.test and not area.doc:
		raise SchemaError(f"{path.name}: 'doc' is missing")
	area.functions = [parse_function(entry, area, path) for entry in raw["functions"]]

	seen = set()
	for function in area.functions:
		if function.id in seen:
			raise SchemaError(f"{path.name}: {function.id}: 'id' is used twice")
		seen.add(function.id)
	members = {}
	for function in area.functions:
		members.setdefault(function.member, []).append(function)
	for member, group in members.items():
		kinds = sorted(function.kind for function in group)
		if kinds not in (["getter"], ["setter"], ["method"], ["getter", "setter"]):
			raise SchemaError(f"{path.name}: {group[-1].id}: member '{member}' is declared twice")
		if kinds == ["getter", "setter"]:
			getter = next(function for function in group if function.kind == "getter")
			setter = next(function for function in group if function.kind == "setter")
			if setter.params[0].type != getter.returns or setter.params[0].kind != getter.return_kind:
				raise SchemaError(f"{path.name}: {setter.id}: sets {setter.params[0].type}, '{member}' gets {getter.returns}")
	return area


def load_areas(directory):
	return [parse_area(path) for path in sorted(directory.glob("*.json"), key=lambda path: path.name)]


def input_digest(directory, script):
	value = FNV_OFFSET
	for path in sorted(directory.glob("*.json"), key=lambda path: path.name):
		value = fnv1a(path.name.encode("utf-8") + b"\0" + path.read_bytes() + b"\0", value)
	return fnv1a(script.read_bytes(), value)


def layout_hash(areas):
	lines = [f"lowering {LOWERING}"] + [f"{name}{{{','.join(fields)}}}" for name, fields in VALUES.items()]
	for area in areas:
		for function in area.functions:
			params = ",".join(("span<" + param.type + ">" if param.kind == "span" else param.type) + ("&" if param.out else "")
							  for param in function.params)
			lines.append(f"{area.name}.{function.id}:{function.returns}({params}){'|leaf' if function.leaf else ''}")
	return fnv1a(("\n".join(lines) + "\n").encode("utf-8"))


def c_type(kind, type_name):
	if kind == "void":
		return "void"
	if kind == "scalar":
		return SCALARS[type_name][0]
	return "Slt" + type_name if type_name in WIDE else "::Shalltear::" + type_name


def cs_abi_type(kind, type_name):
	if kind == "void":
		return "void"
	return SCALARS[type_name][1] if kind == "scalar" else type_name


def cs_api_type(kind, type_name):
	if kind == "void":
		return "void"
	return SCALARS[type_name][2] if kind == "scalar" else type_name


def c_parameters(function, thunk):
	suffix = "In" if thunk else ""
	parts = []
	for param in function.params:
		if param.kind == "scalar":
			parts.append(f"{SCALARS[param.type][0]} {param.name}{suffix if param.type == 'bool' else ''}")
		elif param.kind == "value":
			parts += [f"float {param.name}{field.upper()}" for field in VALUES[param.type]]
		elif param.kind == "string":
			parts.append(f"SltString {param.name}{suffix}")
		else:
			parts.append(f"{'' if param.out else 'const '}{SCALARS[param.type][0]}* {param.name}{'Data' if thunk else ''}")
			parts.append(f"int32_t {param.name}Count")
	if function.guarded and function.return_kind != "void":
		parts.append(f"{c_type(function.return_kind, function.returns)}* outResult")
	return parts


def c_return(function):
	return "int32_t" if function.guarded else c_type(function.return_kind, function.returns)


def render_native_header(areas, digest):
	out = [f"// {BANNER}", "#pragma once", ""]
	out += [f'#include "{header}"' for header in VALUE_HEADERS]
	out += ["", "#include <stdint.h>", "",
			f"#define SLT_BRIDGE_LAYOUT_HASH 0x{layout_hash(areas):016x}ull",
			f"#define SLT_BINDINGS_INPUT_DIGEST 0x{digest:016x}ull", "",
			"typedef struct SltString SltString;", ""]
	for name in WIDE:
		out += [f"typedef struct Slt{name} {{", f"\tfloat {', '.join(VALUES[name])};", f"}} Slt{name};", ""]
	out.append("typedef struct SltBindings {")
	for area in areas:
		for function in area.functions:
			parameters = ", ".join(c_parameters(function, False)) or "void"
			out.append(f"\t{c_return(function)} (*{function.table_member})({parameters});")
	out += ["} SltBindings;", "", "namespace Shalltear::CSharpImpl::Generated {", "",
			"\tvoid FillBindings(SltBindings& table);", "", "} // namespace Shalltear::CSharpImpl::Generated", ""]
	return "\n".join(out)


def render_native_table(areas):
	out = [f"// {BANNER}", "", '#include "ScriptBridge.h"', "", "#include <cstddef>", "#include <type_traits>", "",
		   "namespace Shalltear::CSharpImpl::Generated {", ""]
	for name, fields in VALUES.items():
		size = 4 * len(fields)
		slot = f"Slt{name}" if name in WIDE else f"::Shalltear::{name}"
		out.append(f"\tstatic_assert(sizeof(::Shalltear::{name}) == {size} && std::is_trivially_copyable_v<::Shalltear::{name}>);")
		out.append(f"\tstatic_assert(sizeof({slot}) == {size} && alignof({slot}) == 4);")
		for index, field in enumerate(fields):
			out.append(f"\tstatic_assert(offsetof(::Shalltear::{name}, {field}) == {4 * index} && offsetof({slot}, {field}) == {4 * index});")
	out.append("")
	out += [f"\tvoid Fill{area.name}Bindings(SltBindings& table);" for area in areas]
	out += ["", "\tvoid FillBindings(SltBindings& table) {"]
	out += [f"\t\tFill{area.name}Bindings(table);" for area in areas]
	out += ["\t}", "", "} // namespace Shalltear::CSharpImpl::Generated", ""]
	return "\n".join(out)


def cpp_locals(function):
	lines = []
	for param in function.params:
		if param.kind == "scalar" and param.type == "bool":
			lines.append(f"const bool {param.name} = {param.name}In != 0;")
		elif param.kind == "value":
			fields = ", ".join(param.name + field.upper() for field in VALUES[param.type])
			lines.append(f"const ::Shalltear::{param.type} {param.name}({fields});")
		elif param.kind == "string":
			lines.append(f"const std::string_view {param.name} = View({param.name}In);")
		elif param.kind == "span":
			element = ("" if param.out else "const ") + SCALARS[param.type][0]
			lines.append(f"const std::span<{element}> {param.name}({param.name}Data, static_cast<size_t>({param.name}Count));")
	return lines


def cpp_result(function):
	if function.return_kind == "value":
		return f"FromEngine({function.cpp})" if function.returns in WIDE else function.cpp
	if function.returns == "bool":
		return f"static_cast<uint8_t>(({function.cpp}) ? 1 : 0)"
	return f"static_cast<{SCALARS[function.returns][0]}>({function.cpp})"


def render_thunk(function):
	tabs = "\t\t"
	out = [f"{tabs}{c_return(function)} {function.thunk}({', '.join(c_parameters(function, True))}) noexcept {{"]
	if function.guarded:
		out.append(f"{tabs}\treturn ScriptRuntime::Guard([&] {{")
		out += [f"{tabs}\t\t{line}" for line in cpp_locals(function)]
		if function.return_kind == "void":
			out.append(f"{tabs}\t\t{function.cpp};")
		elif function.return_kind == "value" and function.returns not in WIDE:
			out.append(f"{tabs}\t\t::new (static_cast<void*>(outResult)) ::Shalltear::{function.returns}({function.cpp});")
		else:
			out.append(f"{tabs}\t\t*outResult = {cpp_result(function)};")
		out.append(f"{tabs}\t}});")
	else:
		out += [f"{tabs}\t{line}" for line in cpp_locals(function)]
		out.append(f"{tabs}\tstatic_assert(noexcept({function.cpp}));")
		out.append(f"{tabs}\t{function.cpp};" if function.return_kind == "void" else f"{tabs}\treturn {cpp_result(function)};")
	out.append(f"{tabs}}}")
	return out


def render_native_area(area):
	out = [f"// {BANNER}", "", '#include "BindingSupport.h"', "", f'#include "{area.include}"', ""]
	if area.test:
		out += ["#ifdef SLT_CSHARP_TEST_HOOKS", ""]
	out += ["namespace Shalltear::CSharpImpl::Generated {", "", "\tnamespace {", ""]
	for function in area.functions:
		out += render_thunk(function) + [""]
	out += ["\t} // anonymous namespace", "", f"\tvoid Fill{area.name}Bindings(SltBindings& table) {{"]
	out += [f"\t\ttable.{function.table_member} = &{function.thunk};" for function in area.functions]
	out += ["\t}", "", "} // namespace Shalltear::CSharpImpl::Generated", ""]
	if area.test:
		out += ["#else", "", "namespace Shalltear::CSharpImpl::Generated {", "", f"\tvoid Fill{area.name}Bindings(SltBindings&) {{}}", "",
				"} // namespace Shalltear::CSharpImpl::Generated", "", "#endif", ""]
	return "\n".join(out)


def cs_pointer(function):
	types = []
	for param in function.params:
		if param.kind == "span":
			types += [SCALARS[param.type][1] + "*", "int"]
		elif param.kind == "value":
			types += ["float"] * len(VALUES[param.type])
		else:
			types.append("SltString" if param.kind == "string" else cs_abi_type(param.kind, param.type))
	if function.guarded:
		if function.return_kind != "void":
			types.append(cs_abi_type(function.return_kind, function.returns) + "*")
		types.append("int")
	else:
		types.append(cs_abi_type(function.return_kind, function.returns))
	return f"delegate* unmanaged{'[SuppressGCTransition]' if function.leaf else ''}<{', '.join(types)}>"


def render_managed_table(areas):
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable", "#pragma warning disable CS0649", "",
		   "using System.Runtime.InteropServices;", "", "namespace Shalltear.Interop;", "",
		   "[StructLayout(LayoutKind.Sequential)]", "internal unsafe struct SltBindings {"]
	for area in areas:
		for function in area.functions:
			out.append(f"\tpublic {cs_pointer(function)} {function.table_member};")
	out += ["}", "", "internal static unsafe class Bindings {", f"\tinternal const ulong LAYOUT_HASH = 0x{layout_hash(areas):016x};", "",
			"\tinternal static SltBindings table;", "", "\tinternal static string? FindLayoutMismatch() {"]
	for name, fields in VALUES.items():
		size = 4 * len(fields)
		local = name[0].lower() + name[1:]
		out += [f"\t\tif (sizeof({name}) != {size}) {{", f'\t\t\treturn "{name} size " + sizeof({name}) + " (engine {size})";', "\t\t}",
				f"\t\t{name} {local} = default;"]
		for index, field in enumerate(fields):
			out += [f"\t\tif ((byte*)&{local}.{field} - (byte*)&{local} != {4 * index}) {{",
					f'\t\t\treturn "{name}.{field} offset " + ((byte*)&{local}.{field} - (byte*)&{local}) + " (engine {4 * index})";', "\t\t}"]
	out += ["\t\treturn null;", "\t}", "}", ""]
	return "\n".join(out)


def xml_text(text):
	return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def cs_call(area, function, setter):
	lines = []
	if not function.any_thread:
		lines += ["if (Bridge.OffMainThread) {", f'\tBridge.ThrowOffMainThread("{area.class_name}.{function.member}");', "}"]
	arguments = []
	pinned = []
	for param in function.params:
		name = "value" if setter else param.name
		if param.kind == "scalar":
			arguments.append(f"{name} ? (byte)1 : (byte)0" if param.type == "bool" else name)
		elif param.kind == "value":
			arguments += [f"{name}.{field}" for field in VALUES[param.type]]
		elif param.kind == "string":
			lines.append(f"using UTF8Scratch {name}Text = new({name}, stackalloc byte[UTF8Scratch.STACK_BYTES]);")
			arguments.append(f"{name}Text.Text")
		else:
			pinned.append(f"fixed ({SCALARS[param.type][1]}* {name}Data = {name})")
			arguments += [f"{name}Data", f"{name}.Length"]

	body = []
	is_bool = function.returns == "bool"
	if function.guarded:
		if function.return_kind != "void":
			body.append(f"{cs_abi_type(function.return_kind, function.returns)} result;")
			arguments.append("&result")
		body += [f"int status = Bindings.table.{function.table_member}({', '.join(arguments)});", "if (status != Bridge.OK) {",
				 "\tthrow Bridge.LastError();", "}"]
		if function.return_kind != "void":
			body.append("return result != 0;" if is_bool else "return result;")
	else:
		call = f"Bindings.table.{function.table_member}({', '.join(arguments)})"
		if function.return_kind == "void":
			body.append(call + ";")
		else:
			body.append(f"return {call} != 0;" if is_bool else f"return {call};")
	if pinned:
		lines += pinned[:-1] + [pinned[-1] + " {"] + ["\t" + line for line in body] + ["}"]
	else:
		lines += body
	return lines


def cs_parameters(function):
	parts = []
	for param in function.params:
		if param.kind == "string":
			parts.append(f"string {param.name}")
		elif param.kind == "span":
			parts.append(f"{'Span' if param.out else 'ReadOnlySpan'}<{SCALARS[param.type][2]}> {param.name}")
		else:
			parts.append(f"{cs_api_type(param.kind, param.type)} {param.name}")
	return ", ".join(parts)


def render_managed_area(area):
	access = "internal" if area.test else "public"
	out = ["// <auto-generated/>", f"// {BANNER}", "#nullable enable", "", "using System;", ""]
	if area.namespace != "Shalltear.Interop":
		out += ["using Shalltear.Interop;", ""]
	out += [f"namespace {area.namespace};", ""]
	if area.doc:
		out.append(f"/// <summary>{xml_text(area.doc)}</summary>")
	out.append(f"{access} static unsafe partial class {area.class_name} {{")

	emitted = set()
	blocks = []
	for function in area.functions:
		if function.member in emitted:
			continue
		emitted.add(function.member)
		block = []
		if function.kind == "method":
			if function.doc:
				block.append(f"\t/// <summary>{xml_text(function.doc)}</summary>")
			if function.conditional:
				block.append(f'\t[System.Diagnostics.Conditional("{function.conditional}")]')
			if any(param.kind == "string" for param in function.params):
				block.append("\t[System.Runtime.CompilerServices.SkipLocalsInit]")
			block.append(f"\t{access} static {cs_api_type(function.return_kind, function.returns)} {function.member}({cs_parameters(function)}) {{")
			block += ["\t\t" + line for line in cs_call(area, function, False)]
			block.append("\t}")
		else:
			group = [other for other in area.functions if other.member == function.member]
			getter = next((other for other in group if other.kind == "getter"), None)
			setter = next((other for other in group if other.kind == "setter"), None)
			doc = (getter.doc if getter else "") or (setter.doc if setter else "")
			if doc:
				block.append(f"\t/// <summary>{xml_text(doc)}</summary>")
			if getter:
				type_name = cs_api_type(getter.return_kind, getter.returns)
			else:
				type_name = cs_api_type(setter.params[0].kind, setter.params[0].type)
			block.append(f"\t{access} static {type_name} {function.member} {{")
			if getter:
				block += ["\t\tget {"] + ["\t\t\t" + line for line in cs_call(area, getter, False)] + ["\t\t}"]
			if setter:
				block += ["\t\tset {"] + ["\t\t\t" + line for line in cs_call(area, setter, True)] + ["\t\t}"]
			block.append("\t}")
		blocks.append(block)
	for index, block in enumerate(blocks):
		out += block + ([""] if index + 1 < len(blocks) else [])
	out += ["}", ""]
	return "\n".join(out)


def render(areas, digest):
	files = {
		NATIVE / "Bindings.generated.h": render_native_header(areas, digest),
		NATIVE / "Bindings.generated.cpp": render_native_table(areas),
		MANAGED / "Bindings.g.cs": render_managed_table(areas),
	}
	for area in areas:
		files[NATIVE / f"{area.name}.generated.cpp"] = render_native_area(area)
		files[MANAGED / f"{area.name}.g.cs"] = render_managed_area(area)
	return files


def find_stale(files):
	stale = [path for path, text in files.items() if not path.exists() or path.read_bytes() != text.encode("utf-8")]
	for directory, pattern in ((NATIVE, "*.generated.*"), (MANAGED, "*.g.cs")):
		stale += [path for path in sorted(directory.glob(pattern)) if path not in files]
	return stale


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true", help="fail if the committed output differs (don't rewrite it)")
	args = parser.parse_args()

	try:
		areas = load_areas(BINDINGS)
	except SchemaError as error:
		sys.exit(str(error))
	files = render(areas, input_digest(BINDINGS, Path(__file__).resolve()))
	stale = find_stale(files)
	if args.check:
		if stale:
			sys.exit("stale generated C# bindings: " + ", ".join(path.relative_to(ROOT).as_posix() for path in stale) +
					 "\nRun: python Scripts/generate_csharp_bindings.py")
		print(f"C# bindings up to date ({sum(len(area.functions) for area in areas)} function(s) in {len(areas)} area(s))")
		return

	for path in stale:
		if path in files:
			path.parent.mkdir(parents=True, exist_ok=True)
			path.write_bytes(files[path].encode("utf-8"))
		else:
			path.unlink()
		print(f"  -> {path.relative_to(ROOT).as_posix()}")
	print(f"{sum(len(area.functions) for area in areas)} function(s) in {len(areas)} area(s), {len(stale)} file(s) written")


if __name__ == "__main__":
	main()
